#!/usr/bin/env python3
"""Validate mixed-256 AVAX experiments and pack native AVM1 music assets.

Uses only Python's standard library. No re-encoding or PCM changes occur.
"""

import argparse
import struct
from pathlib import Path

STEPS = (1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 18, 22, 26, 31, 36, 42)


def decode_payload(payload, samples):
    """Independent scalar format validator and signed PCM8 reference decoder."""
    offset = 0
    for start in range(0, samples, 256):
        count = min(256, samples - start)
        if offset + 2 > len(payload):
            raise ValueError("truncated frame header")
        seed, parameter = payload[offset : offset + 2]
        offset += 2
        width, predictor, step = (
            parameter >> 6,
            (parameter >> 4) & 3,
            STEPS[parameter & 15],
        )
        if width == 3 or predictor == 3 or (not width and parameter):
            raise ValueError("invalid mixed frame parameter")
        size = ((count - 1) * width + 7) // 8
        if offset + size > len(payload):
            raise ValueError("truncated residual payload")
        bits = int.from_bytes(payload[offset : offset + size], "little")
        offset += size
        previous = older = seed if seed < 128 else seed - 256
        yield previous
        for _ in range(count - 1):
            if width:
                symbol = bits & ((1 << width) - 1)
                bits >>= width
                residual = (
                    (-step, step)[symbol]
                    if width == 1
                    else (-3 * step, -step, step, 3 * step)[symbol]
                )
                prediction = previous
                if predictor:
                    slope = previous - older
                    prediction += slope if predictor == 1 else slope // 2
                value = max(-128, min(127, prediction + residual))
                older, previous = previous, value
            yield previous
        if bits:
            raise ValueError("nonzero frame padding")
    if offset != len(payload):
        raise ValueError("trailing payload bytes")


def native_asset(payload, samples, loop=False):
    if not 0 < samples <= 0xFFFFFFFF or not 0 < len(payload) <= 0xFFFFFF:
        raise ValueError(
            "native music requires nonempty uint24 payload / uint32 sample count"
        )
    # Exhaust the generator, including its final padding/length checks.
    for _ in decode_payload(payload, samples):
        pass
    return (
        b"AVM1"
        + len(payload).to_bytes(3, "little")
        + bytes([int(loop)])
        + struct.pack("<I", samples)
        + payload
    )


def pack_avax(data, loop=False):
    if len(data) < 34:
        raise ValueError("truncated AVAX header")
    magic, version, codec, flags, scales, frame, samples, rate = struct.unpack(
        "<4sBBBBHII", data[:18]
    )
    if (magic, version, codec, flags, scales, frame, rate) != (
        b"AVAX",
        1,
        6,
        0,
        16,
        256,
        15625,
    ):
        raise ValueError("native playback requires mixed-256 AVAX v1 at 15625 Hz")
    if tuple(data[18:34]) != STEPS:
        raise ValueError("native playback requires the canonical scale table")
    return native_asset(data[34:], samples, loop)


def c_array(data, name, cpp=False):
    """Use uint64 chunks so >64 KiB assets never require a large C array bound."""
    chunks = [data[i : i + 65528] for i in range(0, len(data), 65528)]
    qualifier = "constexpr" if cpp else "static const"
    lines = ["/* Generated by avm_audio_pack.py. */", "#include <avm/audio.h>"]
    lines.append(f"{qualifier} AVM_PROGMEM struct {{")
    for i, chunk in enumerate(chunks):
        lines.append(f"    uint64_t part_{i}[{(len(chunk) + 7) // 8}];")
    lines.append(f"}} {name}_storage = {{")
    for chunk in chunks:
        lines.append("    {")
        values = [
            f"0x{int.from_bytes(chunk[i : i + 8], 'little'):016x}ULL"
            for i in range(0, len(chunk), 8)
        ]
        for i in range(0, len(values), 4):
            lines.append("        " + ", ".join(values[i : i + 4]) + ",")
        lines.append("    },")
    lines += ["};", f"#define {name} (&{name}_storage)", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--loop", action="store_true")
    parser.add_argument("--name", help="emit a C header instead of a native binary")
    args = parser.parse_args()
    data = pack_avax(args.input.read_bytes(), args.loop)
    if args.name:
        args.output.write_text(c_array(data, args.name), encoding="utf-8", newline="\n")
    else:
        args.output.write_bytes(data)
    print(
        f"{len(data)} bytes, {int.from_bytes(data[8:12], 'little')} samples at 15625 Hz"
    )


if __name__ == "__main__":
    main()
