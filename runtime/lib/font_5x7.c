#define AVM_U24_LE(value)                                                     \
        (uint8_t)((value) & 0xffu),                                           \
        (uint8_t)(((value) >> 8) & 0xffu),                                    \
        (uint8_t)(((value) >> 16) & 0xffu)

#define AVM_FONT_5X7_OFFSET(index)                                            \
    (AVM_FONT_5X7_IMAGE_BASE + ((index) - AVM_FONT_5X7_FIRST) * AVM_FONT_5X7_IMAGE_BYTES)

