"""Create the >64 KB exporter fixture used by the native audio tests."""
from pathlib import Path
import json
import runpy
import sys

compiler = runpy.run_path(str(Path(__file__).resolve().parents[2] / "tools/avm_music.py"))
# A terminal rest leaves room for every onset before the fixed music end.
data = compiler["compile_source"]("channel 0 { repeat 22000 { c:4ms } r:4ms }")
assert len(data) > 65535
output = Path(sys.argv[1])
output.parent.mkdir(parents=True, exist_ok=True)
storage = data + bytes((-len(data)) % 8)
assembly = [
    '.section .rodata.long_song,"a",@progbits',
    ".balign 1",
    ".globl long_song",
    ".type long_song,@object",
    "long_song:",
]
assembly.extend(
    ".byte " + ", ".join(f"0x{byte:02x}" for byte in storage[offset : offset + 16])
    for offset in range(0, len(storage), 16)
)
assembly.append(f".size long_song,{len(storage)}")
header = "\n".join(
    [
        "/* Generated by generate_large_asset.py. */",
        f"/* Compiled audio size: {len(data)} bytes. */",
        "#include <avm/audio.h>",
        "extern const uint64_t AVM_PROGMEM long_song[];",
        "__asm__(" + json.dumps("\n".join(assembly) + "\n") + ");",
        "",
    ]
)
output.write_text(header, encoding="utf-8")
