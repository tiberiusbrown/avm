// the layout in docs/arch.md. The blocks are built from named fields: the header,
// function range, CFI rows, sites, outgoing calls, and the action pool. Each
// corrupted block differs from its valid neighbor in the one field its comment
// names. The runtime validator must accept every valid block and reject every
// corrupted one, without reading past the declared block size.

