extern "C" int avm_test_main(void) {
    expect(avm_eh_validate_block(address(valid_block)) == 1);
    expect(avm_eh_validate_block(address(bad_magic)) == 0);
    expect(avm_eh_validate_block(address(short_block_size)) == 0);
    expect(avm_eh_validate_block(address(empty_function_range)) == 0);
    expect(avm_eh_validate_block(address(zero_row_count)) == 0);
    expect(avm_eh_validate_block(address(reserved_mask_bit)) == 0);
    expect(avm_eh_validate_block(address(first_row_offset)) == 0);
    expect(avm_eh_validate_block(address(landing_outside)) == 0);
    expect(avm_eh_validate_block(address(cleanup_action)) == 0);
    expect(avm_eh_validate_block(address(truncated_sites)) == 0);
    expect(avm_eh_validate_block(address(site_outside_function)) == 0);
    expect(avm_eh_validate_block(address(call_return_at_start)) == 0);
    expect(avm_eh_validate_block(address(call_bytes_too_large)) == 0);
    expect(avm_eh_validate_block(address(truncated_calls)) == 0);
    expect(avm_eh_validate_block(address(unordered_calls)) == 0);
    expect(avm_eh_validate_block(address(sites_offset_small)) == 0);
    expect(avm_eh_validate_block(address(sites_offset_large)) == 0);
    expect(avm_eh_validate_block(address(sites_offset_equation)) == 0);
    expect(avm_eh_validate_block(address(sites_offset_past_rows)) == 0);
    expect(avm_eh_validate_block(address(next_offset_zero)) == 0);
    expect(avm_eh_validate_block(address(next_offset_backward)) == 0);
    expect(avm_eh_validate_block(address(next_offset_beyond_block)) == 0);
    expect(avm_eh_validate_block(address(next_offset_inconsistent)) == 0);
    expect(avm_eh_validate_block(address(function_count_too_large)) == 0);
    expect(avm_eh_validate_block(address(function_count_too_small)) == 0);
    expect(avm_eh_validate_block(address(truncated_record)) == 0);
    return failures == 0 ? 0 : 1;
}
