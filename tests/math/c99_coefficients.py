"""Reproduce the compact C99 fits using the existing Remez generator."""
from pathlib import Path
import mpmath as mp
from experiment import fit, poly

mp.mp.dps = 80
cache = {}
def asin_tail(z):
    if not z: return mp.mpf(1)/6
    return (mp.asin(mp.sqrt(z))/mp.sqrt(z)-1)/z

def emit(name, fn, lo, hi, degree):
    cs = fit(fn, mp.mpf(lo), mp.mpf(hi), degree, cache, name)
    return [f'static __attribute__((always_inline)) inline float {name}(float x)',
            '{', '    return '+poly('x', cs, False)+';', '}']

def anchored_exp2():
    """Relative Remez exchange for P4 with its constant fixed to one.

    Equivalently approximate (2**x-1)/x with a cubic and weight |x|/2**x.
    This makes the signed weighted errors alternate across the zero anchor.
    The six relative-error extrema contain five active exchange points.
    """
    points=list(map(mp.mpf,['-0.5','-0.4','-0.17','0.39','0.5']))
    for _ in range(20):
        matrix=mp.matrix([[x**j for j in range(1,5)]+
                          [(-1)**i*mp.sign(x)*mp.power(2,x)]
                          for i,x in enumerate(points)])
        solution=mp.lu_solve(matrix,mp.matrix([mp.power(2,x)-1 for x in points]))
        cs=[mp.mpf(1)]+list(solution)[:4]
        def polynomial(x): return mp.polyval(cs[::-1],x)
        def derivative(x):
            return sum(j*cs[j]*x**(j-1) for j in range(1,5))-mp.log(2)*polynomial(x)
        extrema=[mp.mpf('-0.5')]
        left=extrema[0]
        for i in range(1,513):
            right=mp.mpf('-0.5')+mp.mpf(i)/512
            if derivative(left)*derivative(right)<0:
                extrema.append(mp.findroot(derivative,(left,right),solver='anderson'))
            left=right
        extrema.append(mp.mpf('0.5'))
        if len(extrema)!=6: raise RuntimeError('Unexpected anchored exp2 extrema')
        error=lambda x: polynomial(x)/mp.power(2,x)-1
        active=sorted(sorted(extrema,key=lambda x:abs(error(x)),reverse=True)[:5])
        signs=[mp.sign(x)*mp.sign(error(x)) for x in active]
        if any(a==b for a,b in zip(signs,signs[1:])):
            raise RuntimeError('Anchored exp2 errors do not alternate')
        if max(abs(a-b) for a,b in zip(points,active))<mp.mpf('1e-60'): break
        points=active
    else: raise RuntimeError('Anchored exp2 exchange did not converge')
    print('anchored exp2 degree 4 relative fit error',mp.nstr(max(abs(error(x)) for x in extrema),14))
    return ['static __attribute__((always_inline)) inline float avm_exp2_polynomial(float x)',
            '{', '    return '+poly('x',cs,False)+';', '}']

code = ['/* Generated by tests/math/c99_coefficients.py. */',
        '#ifndef AVM_C99_POLY_H', '#define AVM_C99_POLY_H', '#include "fpoly.h"']
code += emit('avm_asin_tail', asin_tail, 0, '0.25', 3)
code += emit('avm_cbrt_poly', lambda x: mp.root(x+mp.mpf('1.5'),3), '-0.5', '0.5', 7)
code += anchored_exp2()
code += ['#endif', '']
Path('runtime/lib/math/c99_poly.h').write_text('\n'.join(code), encoding='utf-8')
