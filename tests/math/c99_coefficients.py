"""Reproduce the compact C99 fits using the existing Remez generator."""
from pathlib import Path
import mpmath as mp
from experiment import fit, poly

mp.mp.dps = 80
cache = {}
def asin_tail(z):
    if not z: return mp.mpf(1)/6
    return (mp.asin(mp.sqrt(z))/mp.sqrt(z)-1)/z

def emit(name, fn, lo, hi, degree):
    cs = fit(fn, mp.mpf(lo), mp.mpf(hi), degree, cache, name)
    return [f'static __attribute__((always_inline)) inline float {name}(float x)',
            '{', '    return '+poly('x', cs, False)+';', '}']

def anchored_relative(name, fn, df, radius, degree):
    """Relative Remez exchange with the constant fixed to one.

    Equivalently approximate (fn(x)-1)/x with weight |x|/fn(x).
    This makes the signed weighted errors alternate across the zero anchor.
    One of the degree+2 extrema is inactive at the constrained optimum.
    """
    radius=mp.mpf(radius)
    count=degree+1
    if degree==4:
        points=[radius*mp.mpf(x) for x in ['-1','-0.8','-0.34','0.78','1']]
    else:
        points=[-radius*mp.cos(mp.pi*i/(count-1)) for i in range(count)]
    for _ in range(20):
        matrix=mp.matrix([[x**j for j in range(1,degree+1)]+
                          [(-1)**i*mp.sign(x)*fn(x)]
                          for i,x in enumerate(points)])
        solution=mp.lu_solve(matrix,mp.matrix([fn(x)-1 for x in points]))
        cs=[mp.mpf(1)]+list(solution)[:degree]
        def polynomial(x): return mp.polyval(cs[::-1],x)
        def derivative(x):
            return sum(j*cs[j]*x**(j-1) for j in range(1,degree+1))*fn(x)-polynomial(x)*df(x)
        extrema=[-radius]
        left=extrema[0]
        for i in range(1,513):
            right=-radius+2*radius*i/512
            if derivative(left)*derivative(right)<0:
                extrema.append(mp.findroot(derivative,(left,right),solver='anderson'))
            left=right
        extrema.append(radius)
        if len(extrema)!=degree+2: raise RuntimeError('Unexpected anchored extrema: '+name)
        error=lambda x: polynomial(x)/fn(x)-1
        active=sorted(sorted(extrema,key=lambda x:abs(error(x)),reverse=True)[:count])
        signs=[mp.sign(x)*mp.sign(error(x)) for x in active]
        if any(a==b for a,b in zip(signs,signs[1:])):
            raise RuntimeError('Anchored errors do not alternate: '+name)
        if max(abs(a-b) for a,b in zip(points,active))<mp.mpf('1e-60'): break
        points=active
    else: raise RuntimeError('Anchored exchange did not converge: '+name)
    print(name,'degree',degree,'relative fit error',mp.nstr(max(abs(error(x)) for x in extrema),14))
    return [f'static __attribute__((always_inline)) inline float {name}(float x)',
            '{', '    return '+poly('x',cs,False)+';', '}']

code = ['/* Generated by tests/math/c99_coefficients.py. */',
        '#ifndef AVM_C99_POLY_H', '#define AVM_C99_POLY_H', '#include "fpoly.h"']
code += emit('avm_asin_tail', asin_tail, 0, '0.25', 3)
code += emit('avm_cbrt_poly', lambda x: mp.root(x+mp.mpf('1.5'),3), '-0.5', '0.5', 7)
code += anchored_relative('avm_exp2_polynomial',lambda x:mp.power(2,x),
                          lambda x:mp.log(2)*mp.power(2,x),'0.5',4)
code += anchored_relative('avm_expm1_small',lambda x:mp.expm1(x)/x if x else mp.mpf(1),
    lambda x:(x*mp.exp(x)-mp.expm1(x))/(x*x) if x else mp.mpf('0.5'),'1',5)
code += anchored_relative('avm_log1p_small',lambda x:mp.log1p(x)/x if x else mp.mpf(1),
    lambda x:(x/(1+x)-mp.log1p(x))/(x*x) if x else mp.mpf('-0.5'),'0.25',5)
code += ['#endif', '']
Path('runtime/lib/math/c99_poly.h').write_text('\n'.join(code), encoding='utf-8')
