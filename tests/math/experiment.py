"""Generate reproducible math candidates, using the existing Remez/table tools.

Only selected coefficients are installed. Save the source tree first with
--save DIR; --restore DIR recovers it. Build/run each candidate through CMake
and avm_bench (see docs/math-runtime/README.md). No compiler flags or interpreter
instructions are changed. --cache avoids repeating high precision Remez fits.
"""
import argparse
import json
from pathlib import Path
import shutil
import struct
import mpmath as mp
from generate_minimax import remez
import generate_sqrt_table as sqrt

ROOT=Path(__file__).resolve().parents[2]
LIB=ROOT/'runtime/lib'

def literal(x): return sqrt.literal(float(x))

def fit(fn,lo,hi,degree,cache,key):
    if key not in cache:
        cache[key]=[str(c) for c in remez(fn,hi,degree,start=lo,verbose=False)]
    return [mp.mpf(c) for c in cache[key]]

def poly(x,cs,horner):
    if horner:
        s=literal(cs[-1])
        for c in cs[-2::-1]: s=f'({s}*{x}+{literal(c)})'
        return s
    return f'AVM_FPOLY{len(cs)}({x}, '+', '.join(literal(c) for c in cs[::-1])+')'

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--save',type=Path); p.add_argument('--restore',type=Path)
    p.add_argument('--exp-degree',type=int,choices=range(3,7))
    p.add_argument('--exp-reduction',choices=['split','base2'])
    p.add_argument('--log-degree',type=int,choices=range(4,9))
    p.add_argument('--log-pieces',type=int,choices=[1,2],default=1)
    p.add_argument('--near-one',action='store_true'); p.add_argument('--horner',action='store_true')
    p.add_argument('--sqrt-intervals',type=int,choices=[16,32,64,128,256,512,1024])
    p.add_argument('--sqrt-degree',type=int,choices=[1,2],default=2)
    p.add_argument('--cache',type=Path,default=ROOT/'build/math-policy/coefficients.json')
    args=p.parse_args()
    files=['math.c']+['math/'+f.name for f in (LIB/'math').iterdir() if f.is_file()]
    if args.save:
        args.save.mkdir(parents=True,exist_ok=True)
        for f in files:
            dest=args.save/f; dest.parent.mkdir(parents=True,exist_ok=True); shutil.copyfile(LIB/f,dest)
        return
    if args.restore:
        for f in args.restore.rglob('*'):
            if f.is_file(): shutil.copyfile(f,LIB/f.relative_to(args.restore))
        return
    cache=json.loads(args.cache.read_text(encoding='utf-8')) if args.cache.exists() else {}
    prefix='/* Generated by tests/math/experiment.py; do not edit. */\n'
    if args.exp_degree:
        d=args.exp_degree
        if args.exp_reduction=='base2':
            cs=fit(lambda r:mp.power(2,r),-mp.mpf('0.5'),mp.mpf('0.5'),d,cache,f'exp2-{d}')
        else:
            cs=fit(mp.exp,-mp.log(2)/2,mp.log(2)/2,d,cache,f'exp{d}')
        code=prefix+'#include "fpoly.h"\nstatic __attribute__((always_inline)) inline float avm_exp_polynomial(float r)\n{\n    return '+poly('r',cs,args.horner)+';\n}\n'
        (LIB/'math/exp_poly.h').write_text(code, encoding='utf-8')
    if args.exp_reduction:
        path=LIB/'math/ef_exp.c'; source=path.read_text(encoding='utf-8')
        a=source.index('    float u=') if '    float u=' in source else source.index('    int k=')
        b=source.index('    float result=',a)
        if args.exp_reduction=='base2':
            reduction="""    float u=x*0x1.715476p0f;
    int k=0;
    float r=u;
    if (magnitude > 0x3eb17218UL) {
        k=(int)(u+(bits >> 31 ? -0.5f : 0.5f));
        r=u-(float)k;
    }
"""
        else:
            reduction="""    int k=0;
    float r=x;
    if (magnitude > 0x3eb17218UL) {
        /* The high product is exact for all possible k (-150..128).
           Keep the low term to avoid large-x reduction cancellation. */
        k=(int)(x*0x1.715476p0f+(bits >> 31 ? -0.5f : 0.5f));
        float scale=(float)k;
        r=(x-scale*0x1.62e3p-1f)-scale*0x1.2fefa2p-17f;
    }
"""
        path.write_text(source[:a]+reduction+source[b:], encoding='utf-8')
    if args.log_degree:
        d=args.log_degree
        lo=mp.mpf(struct.unpack('<f',struct.pack('<I',0x3f3504df))[0])-1
        hi=mp.mpf(struct.unpack('<f',struct.pack('<I',0x3fb504e0))[0])-1
        fn=lambda f: mp.log1p(f)/f/mp.log(2) if f else 1/mp.log(2)
        intervals=[(lo,hi)] if args.log_pieces==1 else [(lo,mp.mpf(0)),(mp.mpf(0),hi)]
        expressions=[]
        for i,(a,b) in enumerate(intervals):
            cs=fit(fn,a,b,d-1,cache,f'log{d}p{args.log_pieces}i{i}')
            expressions.append('f*'+poly('f',cs,args.horner))
        code=prefix+'#include "fpoly.h"\nstatic __attribute__((always_inline)) inline float avm_log2_mantissa(float x)\n{\n    float f=x-1.0f;\n'
        if args.near_one:
            code+='    if (__builtin_fabsf(f) <= 0x1p-4f)\n        return (f-f*f*AVM_FPOLY5(f,0x1.555556p-3f,-0.2f,0.25f,-0x1.555556p-2f,0.5f))*0x1.715476p0f;\n'
        if len(expressions)==2: code+='    if (f < 0) return '+expressions[0]+';\n'
        code+='    return '+expressions[-1]+';\n}\n'
        (LIB/'math/log_poly.h').write_text(code, encoding='utf-8')
    if args.sqrt_intervals:
        sqrt.INTERVALS=args.sqrt_intervals; sqrt.DEGREE=args.sqrt_degree
        (LIB/'math/sqrt_table.h').write_text(sqrt.table(), encoding='utf-8')
    args.cache.parent.mkdir(parents=True,exist_ok=True)
    args.cache.write_text(json.dumps(cache,indent=2)+'\n', encoding='utf-8')

if __name__=='__main__': main()
