"""Generate binary32 C23 math samples from independent Python double math."""
import math
import random
import struct
from pathlib import Path

rng = random.Random(0xc23)
def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]
def lit(x):
    return f32(x).hex() + 'f'

cases = []
def add(op, x, y, n, result):
    if math.isfinite(result) and abs(result) >= 1e-35 and abs(result) <= 3e38:
        cases.append((op, f32(x), f32(y), n, f32(result)))

for i in range(120):
    x = f32(rng.uniform(-2000, 2000))
    for op, f in [('sinpi', math.sin), ('cospi', math.cos), ('tanpi', math.tan)]:
        add(op, x, 0, 0, f(math.pi * x))
    x = f32(rng.uniform(-0.999, 0.999))
    for op, f in [('asinpi', math.asin), ('acospi', math.acos), ('atanpi', math.atan)]:
        add(op, x, 0, 0, f(x) / math.pi)
    y = f32(rng.uniform(-100, 100))
    add('atan2pi', x, y, 0, math.atan2(x, y) / math.pi)
    x = f32(rng.uniform(-37, 38))
    add('exp10', x, 0, 0, 10 ** x)
    x = f32(rng.uniform(-5, 5))
    add('exp10m1', x, 0, 0, math.expm1(x * math.log(10)))
    add('exp2m1', x, 0, 0, math.expm1(x * math.log(2)))
    x = f32(rng.uniform(-0.99, 20))
    for op, scale in [('logp1', 1), ('log2p1', 1 / math.log(2)), ('log10p1', 1 / math.log(10))]:
        add(op, x, 0, 0, math.log1p(x) * scale)
    x = f32(rng.uniform(0.1, 4))
    n = rng.randrange(-8, 9)
    y = f32(rng.uniform(-8, 8))
    add('pown', x, 0, n, x ** n)
    add('powr', x, y, 0, x ** y)
    n = n or 1
    add('rootn', x, 0, n, x ** (1 / n))
    x = f32(rng.uniform(-0.9, 2))
    add('compoundn', x, 0, n, math.exp(n * math.log1p(x)))
    add('rsqrt', x + 1, 0, 0, 1 / math.sqrt(f32(x + 1)))

# Stress exponential reconstruction and large integer exponents.
for _ in range(150):
    x = f32(rng.uniform(0.5, 2.0))
    n = rng.randrange(-120, 121) or 1
    y = f32(rng.uniform(-120, 120))
    add('pown', x, 0, n, x ** n)
    add('powr', x, y, 0, x ** y)
    add('rootn', x, 0, n, x ** (1 / n))
    x = f32(rng.uniform(-0.5, 1.0))
    add('compoundn', x, 0, n, math.exp(n * math.log1p(x)))

for _ in range(200):
    x = f32(rng.uniform(-0.5, 1.0))
    n = rng.randrange(-1000, 1001) or 1
    add('compoundn', x, 0, n, math.exp(n * math.log1p(x)))

for _ in range(100):
    x = f32(rng.uniform(-0.01, 0.01))
    n = rng.randrange(-10000, 10001) or 1
    add('compoundn', x, 0, n, math.exp(n * math.log1p(x)))

# Include values adjacent to important boundaries and small-argument cancellation.
for x in [-0.49999997, -0.25000003, -0.000001, 0.000001, 0.24999999, 0.49999997]:
    x = f32(x)
    for op, f in [('sinpi', math.sin), ('cospi', math.cos), ('tanpi', math.tan)]:
        add(op, x, 0, 0, f(math.pi * x))
    add('exp10m1', x, 0, 0, math.expm1(x * math.log(10)))
    add('exp2m1', x, 0, 0, math.expm1(x * math.log(2)))
    for op, scale in [('logp1', 1), ('log2p1', 1 / math.log(2)), ('log10p1', 1 / math.log(10))]:
        add(op, x, 0, 0, math.log1p(x) * scale)

names = 'sinpi cospi tanpi asinpi acospi atanpi atan2pi exp10 exp10m1 exp2m1 logp1 log2p1 log10p1 pown powr rootn compoundn rsqrt'.split()
lines = ['/* Generated by tests/math/generate_c23_tests.py. */',
         'static const AVM_PROGMEM struct c23_case c23_cases[] = {']
for op, x, y, n, result in cases:
    lines.append(f'    {{{names.index(op)}, {lit(x)}, {lit(y)}, {n}, {lit(result)}}},')
lines.append('};')
Path('tests/runtime/math/c/math_c23_cases.h').write_text('\n'.join(lines) + '\n')
