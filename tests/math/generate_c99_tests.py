"""Deterministic ordinary/boundary C99 fixtures, independently rounded at 100 digits."""
from pathlib import Path
from accuracy_reference import bits, reference, expected_bits, C99_POLICIES

lines=['/* Generated by tests/math/generate_c99_tests.py. */']
for n,p in C99_POLICIES.items():
    words={0,0x80000000,1,0x80000001,0x007fffff,0x807fffff,0x00800000,
           0x80800000,0x7f7fffff,0xff7fffff,0x7f800000,0xff800000,0x7fc12345,0x7f812345}
    for x in [-150,-149,-126,-100,-27,-8,-1,-0.5,-0.0625,-0.0001,0.0001,
              0.0625,0.5,1,2,8,27,88,127,128]:
        u=bits(x)
        for d in [-1,0,1]:
            if 0<=u+d<=0xffffffff: words.add(u+d)
    if n in ['lgammaf','tgammaf']:
        for x in list(range(-43,0))+[-i+0.5 for i in range(1,44)]+[1,2,7,8,2**-17,-2**-17,-100000,-2**32,-2**64]:
            u=bits(x)
            for d in [-1,0,1]: words.add(u+d)
        words.update(range(0x420c290d,0x420c2913))
    if n in ['erff','erfcf']:
        for x in [-11,-10,-9.5,-9,-4,-1.25,1.25,4,8,9,9.19455,9.5,10,10.0542,11]:
            u=bits(x)
            for d in [-2,-1,0,1,2]: words.add(u+d)
    lines += [f'static const AVM_PROGMEM struct math_case {n}_cases[] = {{']
    for a in sorted(words):
        expected=expected_bits(n,a,0,reference(n,a,0))
        approximate = int(n not in ['erff','erfcf'] or (a & 0x7fffffff) != 0 and (a & 0x7fffffff) < 0x7f800000)
        if n=='lgammaf' and a in [bits(1),bits(2)]: approximate=0
        lines.append(f'    {{0x{a:08x}UL,0,0x{expected:08x}UL,{approximate}}},')
    lines += ['};']
lines += ['static int c99_cases(void)', '{']
for n,p in C99_POLICIES.items():
    lines += [f'    if (check_unary_accuracy({n},{n}_cases,sizeof({n}_cases)/sizeof({n}_cases[0]),{p})) return 1;']
lines += ['    return 0;', '}', '']
Path('tests/c/math_c99_cases.h').write_text('\n'.join(lines),encoding='utf-8')
