# Optional regeneration of the compact exceptional-value grid from the C host
# reference's --generate CSV. Keep glibc as the reference: older MinGW complex
# routines lose branch-cut sides and overflow on finite huge magnitudes.
import argparse
parser=argparse.ArgumentParser()
parser.add_argument('--reference-csv',type=Path)
args=parser.parse_args()
if args.reference_csv:
 pairs=[(0,0),(1,1),(0,18),(0,20),(18,0),(20,0),(18,20),(20,18),
        (18,18),(19,19),(16,16),(17,17),(2,2),(4,4)]
 pairs += [(x,y) for x in (6,7,8,9,12,13,14,15) for y in (0,1,4)]
 pairs += [(y,x) for x in (6,7,8,9) for y in (0,1)]
 wanted={x*21+y for x,y in pairs}
 counts={}
 out='/* Generated from complex_reference.c --generate (glibc). */\n'
 out+='static const AVM_PROGMEM struct cx_golden golden[]={\n'
 for row in args.reference_csv.read_text().splitlines():
  k,x,y,r,i=row.split(',');k=int(k);j=counts.get(k,0);counts[k]=j+1
  if j not in wanted:continue
  # Extreme phase accuracy follows AVM's avr-libc reducer, as does scalar
  # math.h. Host glibc quadrants are not a reference for these inputs.
  phase=y if k in (9,10,11,12) else x if k in (3,4,5) else None
  if phase is not None and 0x48000000 < (int(phase,16)&0x7fffffff) < 0x7f800000:
   continue
  # AVM deliberately selects identities for the standard's unspecified cpow
  # zero/nonfinite cases; the finite principal values remain reference tested.
  out+=f'    {{{k},0x{x}UL,0x{y}UL,0x{r}UL,0x{i}UL}},\n'
 out+='};\n'
 Path('tests/c/complex_golden.h').write_text(out)
