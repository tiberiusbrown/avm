"""Independent 100-digit fixtures for ordinary and boundary hyperbolic inputs."""
from pathlib import Path
from accuracy_reference import bits, reference, expected_bits, HYPERBOLIC

lines = ['/* Generated by tests/math/generate_hyperbolic_tests.py. */',
         '#include "math_test.h"']
for name in HYPERBOLIC:
    words = {0, 0x80000000, 1, 0x80000001, 0x007fffff, 0x807fffff,
             0x00800000, 0x80800000, 0x7f7fffff, 0xff7fffff, 0x7f800000,
             0xff800000, 0x7fc12345, 0xffc12345, 0x7f812345, 0xff812345}
    for x in [0.0625, 0.3125, 0.5, 0.75, 1, 1.0001, 1.5, 2, 4, 9, 9.5,
              16, 80, 88.72284, 89.415986, 100, 4096, 2**64]:
        for sign in [-1, 1]:
            u = bits(sign*x)
            words.update(u+d for d in [-1, 0, 1])
    lines += [f'static const AVM_PROGMEM struct math_case {name}_cases[] = {{']
    for a in sorted(words):
        expected = expected_bits(name, a, 0, reference(name, a, 0))
        lines += [f'    {{0x{a:08x}UL,0,0x{expected:08x}UL,1}},']
    lines += ['};']
lines += ['#ifdef __cplusplus', 'extern "C"', '#endif', 'int avm_test_main(void)', '{']
for name in HYPERBOLIC:
    lines += [f'    if (check_unary_accuracy({name}, {name}_cases, sizeof({name}_cases)/sizeof({name}_cases[0]), AVM_HYPERBOLIC)) return 1;']
lines += ['    return 0;', '}', '']
Path('tests/c/math_hyperbolic.c').write_text('\n'.join(lines), encoding='utf-8')
