NAN = 0x7fc00000
def nan(a): return a & 0x7fffffff > 0x7f800000
def snan(a): return nan(a) and not a & 0x400000
def rounded(x, away=False):
    q = Fraction(x)
    if not away: return round(q)
    n = abs(q).__floor__()
    n += abs(q)-n >= Fraction(1,2)
    return -n if q < 0 else n
def rounding(a, away=False):
    x = value(a)
    if not math.isfinite(x): return NAN if nan(a) else a
    n = rounded(x, away)
    return bits(n) if n else a & 0x80000000
def integer(a, width, away=False):
    x = value(a)
    n = rounded(x, away) if math.isfinite(x) else 1 << width
    return n if -(1 << (width-1)) <= n < 1 << (width-1) else -(1 << (width-1))
def binary(name, a, b):
    x,y = value(a),value(b)
    if name in ['remainderf','remquof']:
        if nan(a) or nan(b) or math.isinf(x) or not y: return NAN,0
        if math.isinf(y): return a,0
        n = round(Fraction(x)/Fraction(y))
        r = Fraction(x)-n*Fraction(y)
        return (bits(r) if r else a & 0x80000000), (-1 if n < 0 else 1)*(abs(n)&7)
    if name == 'fdimf':
        return NAN if nan(a) or nan(b) else bits(x-y) if x>y else 0
    maximum = name == 'fmaxmagf'
    if snan(a) or snan(b): return NAN
    if nan(a): return b
    if nan(b): return a
    if abs(x) == abs(y): return a & b if maximum else a | b
    return a if (abs(x)>abs(y)) == maximum else b

