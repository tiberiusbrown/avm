"""Generate exponent windows of 2/pi with 24 product guard bits, at 120 digits."""
import argparse
from pathlib import Path
import mpmath as mp
import struct

def f32(x): return struct.unpack('<f',struct.pack('<f',float(x)))[0]

def small_header():
    return '''/* Split multiples are defined once alongside the large reducer's table. */
#ifndef AVM_SMALL_PIO2_H
#define AVM_SMALL_PIO2_H
struct avm_small_multiple { float high, low; };
#ifdef __AVM__
extern const __attribute__((address_space(1))) struct avm_small_multiple avm_small_pio2[653];
#else
extern const struct avm_small_multiple avm_small_pio2[653];
#endif
#endif
'''

def table():
    mp.mp.dps = 120
    lines = ['/* Generated by tests/math/generate_reduction_table.py at 120 digits.',
             ' * The low 50 bits align the 24-bit fraction plus 24 guard and two',
             ' * quadrant bits. The upper 24 bits extend the coefficient to 48',
             ' * fractional bits in the cold helper. Ten bytes per exponent. */',
             '#ifndef AVM_REDUCTION_TABLE_H', '#define AVM_REDUCTION_TABLE_H',
             '#ifdef __AVM__', '#define AVM_REDUCE_PROGMEM __attribute__((address_space(1)))',
             '#else', '#define AVM_REDUCE_PROGMEM', '#endif',
             '#include "small_pio2.h"',
             'struct avm_reduce_window { uint32_t low, middle; uint16_t high; };',
             'static const AVM_REDUCE_PROGMEM struct avm_reduce_window avm_reduce_windows[128] = {']
    for exponent in range(128):
        c = int(mp.floor((2/mp.pi)*mp.power(2, exponent+49))) & ((1<<74)-1)
        c = (c>>24)|((c&0xffffff)<<50)
        lines.append(f'    {{0x{c&0xffffffff:08x}UL, 0x{(c>>32)&0xffffffff:08x}UL, 0x{c>>64:04x}U}}, /* 2^{exponent} */')
    lines += ['};', '/* Rounded high terms and 100-digit residuals: n=0..652. */',
              'const AVM_REDUCE_PROGMEM struct avm_small_multiple avm_small_pio2[653] = {']
    for n in range(653):
        exact=n*mp.pi/2
        if 0<n<=81:
            # Zero-only refinement is safe if every unequal float lies on
            # the correct side of this rounded single-constant product.
            rounded=f32(n*f32(mp.pi/2))
            u=struct.unpack('<I',struct.pack('<f',rounded))[0]
            below=struct.unpack('<f',struct.pack('<I',u-1))[0]
            above=struct.unpack('<f',struct.pack('<I',u+1))[0]
            if abs(mp.mpf(rounded)-exact)>=min(rounded-below,above-rounded):
                raise RuntimeError(f'Single-constant sign bound failed at quotient {n}')
        high=f32(exact)
        low=f32(exact-mp.mpf(high))
        lines.append(f'    {{{high.hex()}f, {low.hex()}f}}, /* {n} */')
    return '\n'.join(lines+['};', '#undef AVM_REDUCE_PROGMEM', '#endif', ''])

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    path = Path(__file__).resolve().parents[2]/'runtime/lib/math/reduction_table.h'
    generated = table()
    if args.check:
        if path.read_text() != generated: raise SystemExit('Reduction table is stale')
        if path.with_name('small_pio2.h').read_text()!=small_header(): raise SystemExit('Small table declaration is stale')
        print('All 128 windows and 653 split multiples match the independent 120-digit expansion')
    else:
        path.write_text(generated)
        path.with_name('small_pio2.h').write_text(small_header())
