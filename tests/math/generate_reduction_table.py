"""Generate exponent windows of 2/pi with 24 product guard bits, at 120 digits."""
import argparse
from pathlib import Path
import mpmath as mp

def table():
    mp.mp.dps = 120
    lines = ['/* Generated by tests/math/generate_reduction_table.py; 48 fractional bits,',
             ' * 24 guard bits, two quadrant bits. One 10-byte read per reduction. */',
             '#ifndef AVM_REDUCTION_TABLE_H', '#define AVM_REDUCTION_TABLE_H',
             '#ifdef __AVM__', '#define AVM_REDUCE_PROGMEM __attribute__((address_space(1)))',
             '#else', '#define AVM_REDUCE_PROGMEM', '#endif',
             'struct avm_reduce_window { uint32_t low, middle; uint16_t high; };',
             'static const AVM_REDUCE_PROGMEM struct avm_reduce_window avm_reduce_windows[128] = {']
    for exponent in range(128):
        c = int(mp.floor((2/mp.pi)*mp.power(2, exponent+49))) & ((1<<74)-1)
        lines.append(f'    {{0x{c&0xffffffff:08x}UL, 0x{(c>>32)&0xffffffff:08x}UL, 0x{c>>64:04x}U}}, /* 2^{exponent} */')
    return '\n'.join(lines+['};', '#undef AVM_REDUCE_PROGMEM', '#endif', ''])

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    path = Path(__file__).resolve().parents[2]/'runtime/lib/math/reduction_table.h'
    generated = table()
    if args.check:
        if path.read_text() != generated: raise SystemExit('Reduction table is stale')
        print('All 128 windows match the independent 120-digit expansion')
    else: path.write_text(generated)
