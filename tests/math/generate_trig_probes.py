"""Regenerate the matched, focused AVR-cycle benchmark callers and fixtures."""
from pathlib import Path
import math
import struct

ROOT=Path(__file__).resolve().parents[2]
def value(u): return struct.unpack('<f',struct.pack('<I',u))[0]
def bits(x): return struct.unpack('<I',struct.pack('<f',x))[0]
def around(x):
    u=bits(x)
    return [value(u+d) for d in [-1,0,1]]
def signed(xs): return [s*x for x in xs for s in [1,-1]]
DOMAINS={
    'direct':[0.0,-0.0,value(1),-value(1),.125,-.125,.5,-.5],
    'first':signed([1,2,1.25,1.75]),
    'modest':signed([3,4,8,10]),
    'larger':signed([100,1000,10000,32]),
    'cancel':signed(around(2*math.pi)+[float.fromhex('0x1.2d97c8p2')]),
    'boundary':signed(around(2.5*math.pi/2)+[float.fromhex('0x1.2d97c8p1')]),
    'cutoff':signed(around(100000)+[131072]),
    'normal':signed([float.fromhex('0x1.234568p32'),float.fromhex('0x1.234568p64'),float.fromhex('0x1.234568p96'),value(0x7f7fffff)]),
    # Independently selected by the 100-digit coefficient product search.
    'extended':signed([value(u) for u in [0x65f379c6,0x48926054,0x5b86a17b,0x53f00239]]),
    'even':signed([3,6,10,16]),
    'odd':signed([4,8,14,20]),
    'correction':signed([.5,float.fromhex('0x1.921fb6p-1'),float.fromhex('0x1.921fb8p-1'),.786]),
}
KINDS=['loop','identity','outline','inline','quotient','reconstruct','correct','refine','window','sin','cos','tan','sincos','detect','detectbaseline']

def main():
    lines=['/* Generated by tests/math/generate_trig_probes.py. */']
    for i,(name,xs) in enumerate(DOMAINS.items()):
        lines += [('#if' if i==0 else '#elif')+f' TRIG_PROBE_DOMAIN == {i}',
                  'static volatile float probe_inputs[8]={'+','.join(float(x).hex()+'f' for x in xs)+'};',
                  '#if TRIG_PROBE == 5 || TRIG_PROBE == 7',
                  'static volatile uint32_t probe_quotients[8]={'+','.join(str(int(abs(x)*2/math.pi+.5))+'UL' for x in xs)+'};', '#endif']
        def f(x): return value(bits(x))
        if name=='cancel':
            rs=[]
            for x in xs:
                n=int(f(abs(x)*f(4/math.pi))+1)//2
                rs.append(f(f(abs(x)-f(n*float.fromhex('0x1.92p0')))-f(n*float.fromhex('0x1.fb5444p-12'))))
            lines+=['#if TRIG_PROBE == 13 || TRIG_PROBE == 14',
                    'static volatile float probe_remainders[8]={'+','.join(x.hex()+'f' for x in rs)+'};','#endif']
    lines+=['#endif','']
    (ROOT/'bench/c/math_trig_probe_inputs.h').write_text('\n'.join(lines))
    pairs=[(k,d) for d in range(11) for k in [0,1,2,3,9,10,11,12]]
    pairs += [(4,2),(5,2),(7,4),(6,11),(8,7),(8,8),(13,4),(14,4)]
    for k,d in pairs:
        name=f'math_trig_probe_{KINDS[k]}_{list(DOMAINS)[d]}'
        (ROOT/'bench/c'/f'{name}.c').write_text(f'#define TRIG_PROBE {k}\n#define TRIG_PROBE_DOMAIN {d}\n#include "math_trig_probe.h"\n')
    print(f'Generated {len(pairs)} matched probes')

if __name__=='__main__': main()
