"""Reproduce permanent pole, cutoff, quotient-edge and measured worst fixtures."""
from pathlib import Path
import struct
import mpmath as mp

mp.mp.dps=100
def bits(x): return struct.unpack('<I',struct.pack('<f',float(x)))[0]
def value(u): return struct.unpack('<f',struct.pack('<I',u))[0]

def fixture():
    words={0,0x80000000,1,0x80000001,0x007fffff,0x00800000,
           0x7f7fffff,0xff7fffff,0x7f800000,0xff800000,0x7fc12345,
           0x47fffc72,0x47eed934,0x479e1467,0x478f81f7,0x47a6144c,
           0x3f491241,0xe05f6daf,0x4096cbe4,0x48159252,
           0xc7ab64b6,0xc78d8094,0x434b6b0a,0xc2da5737,
           0xee673b0f,0xe45498f2,0x47bd0e90}
    for x in [mp.pi/4,3*mp.pi/4,1,10,100,1000,10000,30000,50000,100000,131072,mp.mpf(2)**20]:
        u=bits(x)
        words.update(u+d for d in range(-2,3))
    for n in [1,2,3,4,16,127,128,129,255,1024,63661,63662,83443]:
        for phase in [mp.mpf(0),mp.mpf('.5')]:
            u=bits((n+phase)*mp.pi/2)
            words.update(u+d for d in range(-2,3))
    words|={u|0x80000000 for u in words}
    lines=['/* Generated by tests/math/generate_trig_regressions.py (100 digits). */',
           '#include "math_test.h"',
           'struct trig_case { uint32_t input, sine, cosine, tangent; };',
           'static const AVM_PROGMEM struct trig_case cases[] = {']
    for u in sorted(words):
        x=mp.mpf(value(u))
        if not mp.isfinite(x): expected=[0x7fc00000]*3
        else:
            expected=[bits(fn(x)) for fn in [mp.sin,mp.cos,mp.tan]]
            if u==0x80000000: expected[0]=expected[2]=0x80000000
        lines.append('    {'+', '.join(f'0x{word:08x}UL' for word in [u,*expected])+'},')
    lines+=['};', 'int avm_test_main(void) {',
            '    for (uint16_t i=0;i<sizeof(cases)/sizeof(*cases);++i) {',
            '        float x=from_bits(cases[i].input),s,c;',
            '        sincosf(x,&s,&c);',
            '        if (check_accuracy_result(sinf(x),cases[i].sine,1,i,AVM_SIN) ||',
            '            check_accuracy_result(cosf(x),cases[i].cosine,1,i,AVM_COS) ||',
            '            check_accuracy_result(tanf(x),cases[i].tangent,1,i,AVM_TAN) ||',
            '            check_accuracy_result(s,cases[i].sine,1,i,AVM_SIN) ||',
            '            check_accuracy_result(c,cases[i].cosine,1,i,AVM_COS)) return 1;',
            '    }', '    return 0;', '}', '']
    return '\n'.join(lines)

if __name__=='__main__':
    path=Path(__file__).resolve().parents[1]/'c/math_trig_regressions.c'
    path.write_text(fixture())
    path.with_name('math_trig_regressions_output.txt').write_text('P\n')
