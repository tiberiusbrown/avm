"""Reproduce trig regressions and refresh fixtures at avr-libc precision."""
from pathlib import Path
import re
import struct
import mpmath as mp
from accuracy_reference import reference, expected_bits

mp.mp.dps=100
def bits(x): return struct.unpack('<I',struct.pack('<f',float(x)))[0]

def fixture():
    words={0,0x80000000,1,0x80000001,0x007fffff,0x00800000,
           0x7f7fffff,0xff7fffff,0x7f800000,0xff800000,0x7fc12345,
           0x47fffc72,0x47eed934,0x479e1467,0x478f81f7,0x47a6144c,
           0x3f491241,0xe05f6daf,0x4096cbe4,0x48159252,
           0xc7ab64b6,0xc78d8094,0x434b6b0a,0xc2da5737,
           0xee673b0f,0xe45498f2,0x47bd0e90,
           0x65f379c6,0x48926054,0x5b86a17b,0x53f00239,
           0x42908365,0x42b6365e,0x42108365,0x4236365e,
           0x4280ce28,0x42a68121,0x42cc341a,0x42f1e713,
           0x42db2849,0x42eae208,
           0x4718ae20,0x472a2ae5,0x473ba7aa,0x474d246f,0x475ea134,
           0x47701df9,0x4780cd5f,0x47924a24,0x4798ae20,0x47a3c6e9,
           0x47aa2ae5,0x47b543ae,0x47bba7aa}
    for x in [mp.pi/4,3*mp.pi/4,1,4,8,10,16,32,64,128,100,1000,1024,10000,30000,50000,100000,131072,mp.mpf(2)**20]:
        u=bits(x)
        words.update(u+d for d in range(-2,3))
    for n in [1,2,3,4,16,127,128,129,255,1024,63661,63662,83443]:
        for phase in [mp.mpf(0),mp.mpf('.5')]:
            u=bits((n+phase)*mp.pi/2)
            words.update(u+d for d in range(-2,3))
    # Pole neighbors also retain the former native/guest cutoff inputs.
    # All now exercise the same unconditional native reduction.
    for n in range(1, 82, 2):
        for side in [-1, 1]:
            u=bits(n*mp.pi/2 + side*mp.mpf(2)**-12)
            words.update(u+d for d in range(-2,3))
    words|={u|0x80000000 for u in words}
    lines=['/* Generated by tests/math/generate_trig_regressions.py (100 digits, avr-libc reduction precision). */',
           '#include "math_test.h"',
           'struct trig_case { uint32_t input, sine, cosine, tangent; };',
           'static const AVM_PROGMEM struct trig_case cases[] = {']
    for u in sorted(words):
        expected=[expected_bits(name,u,0,reference(name,u,0))
                  for name in ['sinf','cosf','tanf']]
        lines.append('    {'+', '.join(f'0x{word:08x}UL' for word in [u,*expected])+'},')
    lines+=['};', 'int avm_test_main(void) {',
            '    for (uint16_t i=0;i<sizeof(cases)/sizeof(*cases);++i) {',
            '        float x=from_bits(cases[i].input),s,c;',
            '        sincosf(x,&s,&c);',
            '        if (check_accuracy_result(sinf(x),cases[i].sine,1,i,AVM_SIN) ||',
            '            check_accuracy_result(cosf(x),cases[i].cosine,1,i,AVM_COS) ||',
            '            check_accuracy_result(tanf(x),cases[i].tangent,1,i,AVM_TAN) ||',
            '            check_accuracy_result(s,cases[i].sine,1,i,AVM_SIN) ||',
            '            check_accuracy_result(c,cases[i].cosine,1,i,AVM_COS)) return 1;',
            '    }', '    return 0;', '}', '']
    return '\n'.join(lines)

def refresh_fixtures(directory):
    """Retain existing inputs and tolerances; update their reference values."""
    row=re.compile(r'(\{\s*)0x([0-9a-fA-F]+)UL,(\s*)0x([0-9a-fA-F]+)UL,(\s*)0x([0-9a-fA-F]+)UL')
    for name in ['sinf','cosf','tanf','sincos_sinf','sincos_cosf']:
        for path in directory.glob('math_'+name+'*.c'):
            def replace(match):
                a,b=int(match[2],16),int(match[4],16)
                expected=expected_bits(name,a,b,reference(name,a,b))
                return f'{match[1]}0x{a:08x}UL,{match[3]}0x{b:08x}UL,{match[5]}0x{expected:08x}UL'
            text=row.sub(replace,path.read_text())
            text=text.replace('Independent host-libm references',
                              'Independent avr-libc-precision references')
            path.write_text(text)
    path=directory/'math_sincosf.c'
    def replace_pair(match):
        a=int(match[2],16)
        s=expected_bits('sinf',a,0,reference('sinf',a,0))
        c=expected_bits('cosf',a,0,reference('cosf',a,0))
        return f'{match[1]}0x{a:08x}UL,{match[3]}0x{c:08x}UL,{match[5]}0x{s:08x}UL'
    text=row.sub(replace_pair,path.read_text())
    text=text.replace('Independent 100-digit mathematical values',
                      'Independent 100-digit values at avr-libc reduction precision')
    path.write_text(text)

if __name__=='__main__':
    path=Path(__file__).resolve().parents[1]/'c/math_trig_regressions.c'
    path.write_text(fixture())
    path.with_name('math_trig_regressions_output.txt').write_text('P\n')
    refresh_fixtures(path.parent)
