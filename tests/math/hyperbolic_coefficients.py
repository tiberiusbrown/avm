"""Generate short, unity-anchored hyperbolic fits for native FPOLY.

Fit (f(sqrt(z))/sqrt(z)-1)/z (or (cosh(sqrt(z))-1)/z).
For acosh, fit (acosh(1+z)/sqrt(2*z)-1)/z on [0,1].
The constant 1 preserves small inputs without a separate tiny-input path.
Only coefficient generation uses wider arithmetic; guest arithmetic is float.
"""
from pathlib import Path
import mpmath as mp
from experiment import poly

mp.mp.dps = 80
specs = [('sinh', mp.sinh, 1, 3, mp.mpf(1)/6),
         ('cosh', mp.cosh, 1, 3, mp.mpf(1)/2),
         ('tanh', mp.tanh, 1, 5, -mp.mpf(1)/3),
         ('asinh', mp.asinh, 1, 5, -mp.mpf(1)/6),
         ('acosh', mp.acosh, 1, 4, -mp.mpf(1)/12),
         ('atanh', mp.atanh, mp.mpf(1)/4, 4, mp.mpf(1)/3)]
lines = ['/* Generated by tests/math/hyperbolic_coefficients.py. */',
         '#ifndef AVM_HYPERBOLIC_POLY_H', '#define AVM_HYPERBOLIC_POLY_H',
         '#include "fpoly.h"']
for name, fn, limit, degree, slope in specs:
    def ratio(z):
        if name == 'acosh':
            return fn(1+z)/mp.sqrt(2*z) if z else mp.mpf(1)
        return fn(mp.sqrt(z)) if name == 'cosh' else fn(mp.sqrt(z))/mp.sqrt(z) if z else mp.mpf(1)
    def correction(z):
        return (ratio(z)-1)/z if z else slope
    cs = [mp.mpf(1)] + list(reversed(mp.chebyfit(correction, [0, limit], degree)))
    error = max(abs(sum(c*(limit*i/4096)**j for j,c in enumerate(cs))/ratio(limit*i/4096)-1)
                for i in range(4097))
    print(name, 'degree', degree, 'real relative error', mp.nstr(error, 12))
    lines += [f'static __attribute__((always_inline)) inline float avm_{name}_small(float z)',
              '{', '    return '+poly('z', cs, False)+';', '}']
lines += ['#endif', '']
(Path(__file__).resolve().parents[2]/'runtime/lib/math/hyperbolic_poly.h').write_text('\n'.join(lines))
