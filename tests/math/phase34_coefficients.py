"""Reproduce reduced-range Remez fits for the phase 3/4 experiment.

Writes only the requested coefficient header. Production has a single selected
implementation; experiment headers and measurements belong under build/.
"""
import argparse
import json
import struct
from pathlib import Path
import mpmath as mp
from experiment import fit, poly, literal


def generate(args):
    cache_path = Path('build/math-phase34/coefficients.json')
    cache = json.loads(cache_path.read_text()) if cache_path.exists() else {}
    # The reducer can round pi/4 upward; include the binary32 x*x endpoint.
    quarter=struct.unpack('<f',struct.pack('<I',0x3f490fdb))[0]
    end=mp.mpf(struct.unpack('<f',struct.pack('<f',quarter*quarter))[0])
    def sinc(z): return mp.sin(mp.sqrt(z))/mp.sqrt(z) if z else mp.mpf(1)
    def cos(z): return mp.cos(mp.sqrt(z))
    def tanc(z): return (mp.tan(mp.sqrt(z))/mp.sqrt(z)-1)/z if z else mp.mpf(1)/3
    def atanc(z): return mp.re(mp.atan(mp.sqrt(z))/mp.sqrt(z)) if z else mp.mpf(1)
    def polynomial(fn,a,b,d,key,x):
        if args.anchor_ends and key.startswith('atan') and d>=2:
            slope=(fn(b)-fn(a))/(b-a)
            intercept=fn(a)-slope*a
            def residual(t):
                # Remez differentiates at endpoints; compute the divided
                # difference with enough guard digits for nested differences.
                with mp.extradps(200):
                    linear=(fn(b)-fn(a))/(b-a)
                    offset=fn(a)-linear*a
                    if t==a: return (mp.diff(fn,a)-linear)/(a-b)
                    if t==b: return (mp.diff(fn,b)-linear)/(b-a)
                    return (fn(t)-(offset+linear*t))/((t-a)*(t-b))
            rs=fit(residual,a,b,d-2,cache,key+'-anchored')
            cs=[intercept,slope]+[mp.mpf(0)]*(d-1)
            for i,r in enumerate(rs):
                cs[i]+=a*b*r
                cs[i+1]-=(a+b)*r
                cs[i+2]+=r
        else: cs=fit(fn,a,b,d,cache,key)
        if len(cs)<=8 or args.horner: return poly(x,cs,args.horner)
        expr=poly(x,cs[-8:],False)
        for c in cs[-9::-1]: expr=f'({expr}*{x}+{literal(c)})'
        return expr
    guard='AVM_'+args.output.name.upper().replace('.','_')
    code=['/* Generated by tests/math/phase34_coefficients.py. */',
          f'#ifndef {guard}',f'#define {guard}', '#include "fpoly.h"']
    for name, fn, d in [('sin',sinc,args.sin),('cos',cos,args.cos),('tan',tanc,args.tan)]:
        if d is not None:
            code += [f'static __attribute__((always_inline)) inline float avm_{name}_polynomial(float z)',
                     '{']
            for i in range(args.trig_pieces):
                a=end*i/args.trig_pieces; b=end*(i+1)/args.trig_pieces
                key=f'{name}-{d}-binary32-p{args.trig_pieces}-i{i}'
                expression=polynomial(fn,a,b,d,key,'z')
                if i<args.trig_pieces-1: code += [f'    if (z <= {literal(b)}) return {expression};']
                else: code += [f'    return {expression};']
            code += ['}']
    if args.pow_log_degree:
        lo=mp.mpf(struct.unpack('<f',struct.pack('<I',0x3f3504df))[0])-1
        hi=mp.mpf(struct.unpack('<f',struct.pack('<I',0x3fb504e0))[0])-1
        expr=polynomial(lambda f:mp.log1p(f)/f/mp.log(2) if f else 1/mp.log(2),
                        lo,hi,args.pow_log_degree-1,f'pow-log2-{args.pow_log_degree}-binary32','f')
        code += ['static __attribute__((always_inline)) inline float avm_pow_log2_mantissa(float x)',
                 '{','    float f=x-1.0f;',f'    return f*{expr};','}']
    if args.atan is not None:
        code += ['static __attribute__((always_inline)) inline float avm_atan_unit(float x)', '{']
        if args.pieces==1:
            expr=polynomial(atanc,0,1,args.atan,f'atan-odd-{args.atan}','z')
            code += ['    float z=x*x;',f'    return x*{expr};']
        else:
            # Odd first interval preserves signed zero and relative accuracy
            # at axes; the remaining centered polynomials need no division.
            edge=mp.mpf(1)/args.pieces
            code += ['    uint32_t ix;','    GET_FLOAT_WORD(ix,x);',
                     '    uint16_t interval=(uint16_t)(ix>>16);']
            def interval_test(edge):
                word=struct.unpack('<I',struct.pack('<f',float(edge)))[0]
                assert word&0xffff==0
                return f'interval < 0x{word>>16:04x}U'
            expr=polynomial(atanc,0,edge**2,args.atan,f'atan-low-{args.pieces}-{args.atan}','z')
            blocks=[['float z=x*x;',f'return x*{expr};']]
            for i in range(1,args.pieces):
                center=(mp.mpf(i)+mp.mpf('0.5'))/args.pieces
                half=edge/2
                expr=polynomial(lambda t:mp.atan(t+center),-half,half,args.atan+1,
                                f'atan-{args.pieces}-{i}-{args.atan+1}','t')
                blocks.append([f'float t=x-{float(center).hex()}f;',f'return {expr};'])
            def emit(first,last,indent):
                if last-first==1:
                    code.extend(indent+line for line in blocks[first]); return
                middle=(first+last)//2 if args.balanced else first+1
                code.append(indent+f'if ({interval_test(edge*middle)}) {{')
                emit(first,middle,indent+'    ')
                code.append(indent+'} else {')
                emit(middle,last,indent+'    ')
                code.append(indent+'}')
            emit(0,args.pieces,'    ')
        code += ['}']
    cache_path.parent.mkdir(parents=True,exist_ok=True)
    cache_path.write_text(json.dumps(cache,indent=2)+'\n')
    args.output.write_text('\n'.join(code+['#endif'])+'\n')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for name in ['sin','cos','tan','atan']: p.add_argument('--'+name,type=int)
    p.add_argument('--pieces',type=int,default=2)
    p.add_argument('--trig-pieces',type=int,default=1)
    p.add_argument('--pow-log-degree',type=int)
    p.add_argument('--horner',action='store_true')
    p.add_argument('--balanced',action='store_true')
    p.add_argument('--anchor-ends',action='store_true')
    p.add_argument('--output',type=Path,required=True)
    generate(p.parse_args())
