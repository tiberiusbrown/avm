"""Render committed Markdown math reports from measured JSON/text artifacts.

--import-experiments copies a compact, path-independent summary of build-tree
trials into docs/math-runtime/candidates.json. Ordinary regeneration uses only
committed inputs and is deterministic. No hard-coded numerical measurements.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[2]
DOCS=ROOT/'docs/math-runtime'

def load(path): return json.loads(path.read_text(encoding='utf-8'))
def cycles(path):
    return {s[1].removesuffix('.c'):int(s[0]) for line in path.read_text(encoding='utf-8').splitlines() if len(s:=line.split())==2}
def number(x): return f'{x:.9g}'
def inputs(pair): return '`'+', '.join(pair)+'`' if pair else '-'
def table(headers,rows):
    return '\n'.join(['| '+' | '.join(headers)+' |','| '+' | '.join(['---']*len(headers))+' |']+['| '+' | '.join(map(str,r))+' |' for r in rows])
def symbols(resource):
    result={}
    for obj,data in resource['symbols'].items():
        for line in data['defined'].splitlines():
            cols=line.split()
            if len(cols)==4: result[cols[3]]=int(cols[1],16)
    return result

def accuracy():
    data=load(DOCS/'accuracy.json'); baseline=load(DOCS/'baseline-accuracy.json')
    rows=[]
    for n,s in data['functions'].items():
        rows.append([n,f"{s['count']:,}",number(s['max_absolute']),inputs(s['worst_absolute']),number(s['max_relative_normal']),inputs(s['worst_relative']),int(s['max_ulp']),inputs(s['worst_ulp']),f"{s['failures']} ({s['failure_percent']:.6g}%)",s['exceptional_changes']])
    text='''<!-- Generated by tests/math/render_report.py; do not edit measurements. -->
# Measured math accuracy

Measurements use the production kernels and the existing FPOLY reference model,
with independent mpmath references at 100 decimal digits. See [policy and
commands](README.md) for domains, acceptance formulas and sample construction.
These maxima describe the measured corpus; exhaustive coverage is identified
separately below. Hex inputs are exact binary32 words; a second word is used
only by binary functions. Relative maxima exclude subnormal reference outputs.
ULP distances are to correctly rounded binary32 references. NaNs compare by
classification; signs of infinity and zero are checked independently.

'''
    text+=table(['Function','Cases','Max absolute','Worst abs input(s)','Max relative (normal)','Worst relative input(s)','Max ULP','Worst ULP input(s)','Failures','Exceptional changes'],rows)+'\n\n'
    text+='## Distribution of measured errors\n\n'
    text+=table(['Function','0 ULP','1 ULP','2–4 ULP','5–16 ULP','17+ ULP'],[[n,*s['ulp_distribution']] for n,s in data['functions'].items()])+'\n\n'
    text+='## Input ranges\n\n'
    text+=table(['Function','Range','Finite cases','Max ULP','Failures'],[[n,r,v['count'],v['max_ulp'],v['failures']] for n,s in data['functions'].items() for r,v in s['ranges'].items()])+'\n\n'
    text+='## Unchanged baseline\n\nSame initial corpus and precision, with independent adaptive searches for each implementation.\n\n'
    text+=table(['Function','Cases','Max absolute','Max relative (normal)','Max ULP','Failures'],[[n,s['count'],number(s['max_absolute']),number(s['max_relative_normal']),int(s['max_ulp']),s['failures']] for n,s in baseline['functions'].items()])+'\n\n'
    text+='## Exhaustive and dense production checks\n\n'
    text+='The existing native checks also compare against independent double libm.\nTheir larger domains complement the high-precision search above.\n\n'
    for filename in ['sqrt.txt','dense.txt']:
        if (DOCS/filename).exists(): text+='```text\n'+(DOCS/filename).read_text(encoding='utf-8').strip()+'\n```\n\n'
    text+='The square-root histogram counts comparisons with both independent references,\nnot unique inputs. Square-root normalization and power-of-two scaling are exact;\nall 16,777,216 normalized mantissa/parity inputs and 8,388,607 positive\nsubnormals are exhausted. Exact square and signed-zero fixtures remain.\n'
    (DOCS/'accuracy.md').write_text(text, encoding='utf-8')

def report():
    before=cycles(DOCS/'baseline-cycles.txt'); after=cycles(DOCS/'cycles.txt')
    bres=load(DOCS/'baseline-resources.json'); ares=load(DOCS/'resources.json')
    bs,as_=symbols(bres),symbols(ares)
    data=load(DOCS/'accuracy.json')
    text='''<!-- Generated by tests/math/render_report.py; do not edit measurements. -->
# AVM math runtime, phases 1–2

The selected kernels remove exact-root correction and division-based exp/log
approximations. The interpreter and trig reducer are unchanged. The table below
uses the real AVR interpreter, identical deterministic callers, RelWithDebInfo,
-O2 callers and -O3 -ffp-contract=off runtime math. Cycles include loop/input/result
costs and subtract the adjacent DEBUG_BREAK baseline (35 AVR cycles).

'''
    names=['sqrt','exp','log','log2','log10','hypot','pow']
    text+=table(['Function','Before cycles/call','After cycles/call','Speedup'],[[n+'f',f"{before['math_'+n]/32:.2f}",f"{after['math_'+n]/32:.2f}",f"{before['math_'+n]/after['math_'+n]:.3f}x"] for n in names])+'\n\n'
    text+='## Workloads\n\n'
    selected=[n for n in after if any(n.startswith('math_'+f) for f in names)]
    text+=table(['Workload','Calls','Before cycles/call','After cycles/call','Speedup'],[[n,256 if n=='math_sqrt_random' else 32,f"{before[n]/(256 if n=='math_sqrt_random' else 32):.2f}",f"{after[n]/(256 if n=='math_sqrt_random' else 32):.2f}",f"{before[n]/after[n]:.3f}x"] for n in selected])+'\n\n'
    text+='The ordinary exp/log/pow inputs span 0.25–1.21875; pow uses exponent 1.25.\nThe sqrt workload spans positive subnormals, exponent parities, powers of two\nand extreme magnitudes. Scaled workloads add gradual underflow, extreme\nexponents and reduction boundaries. Near-one workloads include neighbors of\none, polynomial endpoints and powers of two. sqrt_random covers every finite\nexponent. See bench/README.md and the committed C sources for exact inputs.\n\n'
    text+='## Selected algorithms\n\n'
    text+='''Square root uses 512 linear intervals per exponent parity, one uninterrupted
8-byte coefficient read, one multiply and one add, followed by exact exponent
packing. The 8 KiB guest table trades external program storage for speed. The
original 64-interval quadratic without correction exhaustively stayed within
1 ULP. A 32-interval quadratic and the selected linear table reached 2 ULP.
A 1024-interval linear table stayed within 1 ULP but was slower on every direct
sqrt workload and doubled table storage. It was slightly faster for ordinary
hypot; the 512-interval table wins the direct-function workload selection.

Exponential uses x*log2(e), a centered integer decomposition, a degree-4 Remez
polynomial for 2^r on [-0.5,0.5], and exponent-word scaling. The existing cutoff
classification and staged multiply for subnormal outputs remain. The direct
base-two reduction is faster than split-ln2 reduction and passes the relaxed
relative budget. Degree 3 fails; degrees 5 and 6 cost more. The primary interval
avoids integer conversion. Tiny x returns 1+x, preserving exp(0)=1.

The logarithms normalize into approximately [sqrt(1/2),sqrt(2)], then evaluate
f*P6(f) for log2(1+f), preserving log(1)=0 and small-result signs. The exponent
is added in base two; log/log10 use one conversion multiply. All three inline
the shared core; calls to a shared external log2 engine were slower. A single
degree-7 polynomial beats two degree-5 pieces despite the latter's shorter
polynomials. The retained near-one specialization experiment was slower; the
selected factored polynomial is already stable near one. pow uses the updated
shared logarithm/exponential only on its existing bounded shortcut. Its general
fdlibm decomposition and integer-power shortcuts are unchanged.

'''
    text+='## Numerical results\n\n'
    text+=f"The 100-digit reference search records {sum(s['count'] for s in data['functions'].values()):,} results, {sum(s['failures'] for s in data['functions'].values())} acceptance failures and {sum(s['exceptional_changes'] for s in data['functions'].values())} exceptional-behavior changes. "
    text+='[Generated accuracy tables](accuracy.md) include every maximum, worst input, failure percentage, ULP distribution and range breakdown. The accompanying JSON is the machine-readable measurement record. Dense/exhaustive output is retained alongside it.\n\n'
    text+='## Resources\n\n'
    text+=table(['Guest symbol','Before bytes','After bytes','Change'],[[n,bs.get(n,0),as_.get(n,0),as_.get(n,0)-bs.get(n,0)] for n in ['sqrtf','sqrt_table','expf','logf','log2f','log10f','hypotf','powf']])+'\n\n'
    text+=table(['Linked workload image','Before bytes','After bytes','Change'],[[n,bres['image_bytes'][n],ares['image_bytes'][n],ares['image_bytes'][n]-bres['image_bytes'][n]] for n in ['math_'+s for s in names]])+'\n\n'
    for file,label in [('baseline-stack.tsv','Before'),('stack.tsv','After')]:
        lines=[r.split('\t') for r in (DOCS/file).read_text(encoding='utf-8').splitlines()[1:]]
        relevant=[r for r in lines if r[0] in selected]
        text+=label+' stack usage:\n\n'+table(['Workload','Peak guest bytes (of 256)','Extra native bytes'],relevant)+'\n\n'
    same=bres['interpreter_sha256']==ares['interpreter_sha256']
    text+='Interpreter HEX SHA-256 '+('is identical before/after' if same else 'DIFFERS')+': `'+ares['interpreter_sha256']+'`. '
    if (DOCS/'validation.json').exists():
        validation=load(DOCS/'validation.json')
        text+=f"Flash data: {validation['interpreter_flash_bytes']:,} bytes. "
    text+='No native instructions or interpreter files were modified.\n\n'
    text+='Undefined symbols of the affected objects (new minus baseline):\n\n'
    for obj,r in ares['symbols'].items():
        old=set(bres['symbols'][obj]['undefined'].splitlines()); new=set(r['undefined'].splitlines())
        text+='- `'+obj+'`: '+(', '.join('`'+x.strip()+'`' for x in sorted(new-old)) or 'none')+'.\n'
    text+='\nThe original general pow helpers remain; root, exp and log add no wide-integer\nhelpers. Selected exp/log approximation paths contain no floating-point division. The\nlogarithms retain one cold fdiv for the existing negative-input NaN path. FPOLY\nembeds coefficients and avoids their loading/spilling costs; ordinary Horner\nwas measurably slower. The square-root record offset is a native word and its\n8-byte stride becomes a constant shift. Generated benchmark disassemblies are\nretained under bench/c/asm; production disassembly is regenerated by avm_runtime_asm.\n\n'
    if 'instruction_counts' in ares:
        rows=[]
        for obj in ['math_ef_sqrt','math_ef_exp','math_ef_log','math','math_ef_log10']:
            for op in ['fdiv','fmul','fadd','fpoly','ldsp16','stsp16']:
                rows.append([obj,op,bres['instruction_counts'][obj].get(op,0),ares['instruction_counts'][obj].get(op,0)])
        text+='Static disassembly counts include mutually exclusive paths (not dynamic costs).\nThe remaining log fdiv is exclusively the negative-domain exceptional path.\n\n'
        text+=table(['Object','Instruction','Before','After'],rows)+'\n\n'
    text+='## Alternatives measured\n\n'
    if (DOCS/'candidates.json').exists():
        experiments=load(DOCS/'candidates.json')
        rows=[]
        for label,v in experiments.items():
            s=v['accuracy']['functions']; c=v['cycles']
            relevant='sqrtf' if label.startswith('sqrt') else 'log2f' if label.startswith('log') else 'expf'
            rows.append([label,c['math_sqrt'],c['math_exp'],c['math_log'],number(s[relevant]['max_absolute']),number(s[relevant]['max_relative_normal']),int(s[relevant]['max_ulp']),sum(x['failures'] for x in s.values()),v.get('sqrt_exhaustive','-')])
        text+=table(['Candidate','sqrt cycles/32','exp cycles/32','log cycles/32','Relevant max abs','Relevant max rel','Relevant max ULP','Acceptance failures','Exhaustive sqrt'],rows)+'\n\n'
        text+='One family changes at a time in the first matrix; later base-two exp rows use\nthe 1024-interval root, and the final selected row combines the winners. Raw\nper-function numerical results, workload cycles and image resources for all\ntrials are preserved in candidates.json. Rejected square-root trials terminate\non their first >2-ULP example; passing trials complete the entire old domain.\n\n'
    text+='## Verification and reproduction\n\n'
    if (DOCS/'validation.json').exists():
        v=load(DOCS/'validation.json')
        text+=table(['Check','Result'],[[k,val] for k,val in v.items() if k!='interpreter_flash_bytes'])+'\n\n'
    text+='See [commands and precise policy](README.md). No\nfull pow rewrite, trig redesign, global semantic relaxation, or new native\ninstruction is included.\n'
    (DOCS/'report.md').write_text(text, encoding='utf-8')

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--import-experiments',type=Path)
    a=p.parse_args()
    if a.import_experiments:
        experiments={}
        for file in sorted(a.import_experiments.glob('*/accuracy.json')):
            directory=file.parent
            v=dict(accuracy=load(file),cycles=cycles(directory/'cycles.txt'))
            if (directory/'resources.json').exists(): v['resources']=load(directory/'resources.json')
            if (directory/'sqrt.txt').exists():
                txt=(directory/'sqrt.txt').read_text(encoding='utf-8'); m=re.search(r'max (\d+) ULP',txt)
                v['sqrt_exhaustive']='pass, max '+m[1]+' ULP' if m else txt.strip()
            experiments[directory.name]=v
        (DOCS/'candidates.json').write_text(json.dumps(experiments,indent=2)+'\n', encoding='utf-8')
    accuracy(); report()

if __name__=='__main__': main()
