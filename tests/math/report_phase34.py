"""Render the phase 3/4 report from its committed measurement records."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil

ROOT=Path(__file__).resolve().parents[2]
DOCS=ROOT/'docs/math-runtime/phase34'
FUNCTIONS={'powf':'pow','hypotf':'hypot','sinf':'sin','cosf':'cos',
           'tanf':'tan','atanf':'atan','atan2f':'atan2','sincosf':'sincos'}
OBJECTS={'powf':'math_ef_pow','hypotf':'math_ef_hypot','sinf':'math_sf_sin',
         'cosf':'math_sf_cos','tanf':'math_sf_tan','atanf':'math_sf_atan',
         'atan2f':'math_ef_atan2','sincosf':'math_sf_sincos'}


def cycles(name):
    return {m[2].removesuffix('.c'):int(m[1]) for line in (DOCS/name).read_text().splitlines()
            if (m:=re.match(r'\s*(\d+)\s+(\S+)',line))}


def stacks(name):
    return {r[0]:(int(r[1]),int(r[2])) for line in (DOCS/name).read_text().splitlines()[1:]
            if len(r:=line.split())==3}


def size(resources,obj):
    return sum(int(m[1],16) for line in resources['symbols'].get(obj,{}).get('defined','').splitlines()
               if (m:=re.match(r'\S+\s+([0-9a-f]+)\s+',line)))


def refresh():
    build=ROOT/'build/math-phase34'
    log=(build/'regressions-final.log').read_text()
    passed=re.search(r'All (\d+) AVM test\(s\) passed\.',log)
    assert passed and not re.search(r'^FAIL|FAILED:|\] .*FAIL$',log,re.M), 'Regression run did not pass'
    for label in ['baseline','final']:
        for n in ['cycles.txt','stack.tsv','resources.json']:
            source=build/label/n
            if source.exists(): shutil.copyfile(source,DOCS/f'{label}-{n}')
    prefixes=('hypotf:','atan2f:','atanf:','tanf:','logf:','log2f:','log10f:',
              'powf:','expf:','fmodf:','sinf:','cosf:','tanf_policy:')
    dense=[l for l in log.splitlines() if l.startswith(prefixes)]
    assert len(dense)==13
    (DOCS/'dense.txt').write_text('\n'.join(dense)+'\n')
    summary=[l for l in log.splitlines() if not l.startswith('[') and
             ('passed' in l or 'verified' in l or 'free of' in l)]
    (DOCS/'validation.txt').write_text('\n'.join(summary)+'\n')
    image=ROOT/'interp/build/interp.hex'
    flash_bytes=sum(int(l[1:3],16) for l in image.read_text().splitlines()
                    if l.startswith(':') and l[7:9]=='00')
    validation=dict(guest_suite_exit_code=0,guest_test_count=int(passed[1]),
        command='cmake --build build --config RelWithDebInfo --target avm_tests_run avm_audio_tests_run avm_runtime_asm --parallel 8',
        optimization_levels=['O0','O1','O2','O3','Os','Oz'],runtime_optimization='O3',
        interpreter_flash_bytes=flash_bytes,interpreter_sha256=hashlib.sha256(image.read_bytes()).hexdigest(),
        coefficient_reproduction='Selected headers reproduced byte for byte',
        sqrt_table_check='tests/math/generate_sqrt_table.py --check passed',
        logs=['validation.txt','dense.txt','accuracy.json'])
    (DOCS/'validation.json').write_text(json.dumps(validation,indent=2)+'\n')
    rows={}
    for p in build.glob('*/accuracy.json'):
        if p.parent.name in ['baseline','final']: continue
        stats=json.loads(p.read_text())['functions']
        rows[p.parent.name]=dict(failures={n:s['failures'] for n,s in stats.items()},
            cycles={m[2].removesuffix('.c'):int(m[1]) for line in p.with_name('cycles.txt').read_text().splitlines()
                    if (m:=re.match(r'\s*(\d+)\s+(\S+)',line))})
    if rows: (DOCS/'candidates.json').write_text(json.dumps(rows,indent=2)+'\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh',action='store_true',help='Import completed build/math-phase34 measurements')
    if parser.parse_args().refresh: refresh()
    before=cycles('baseline-cycles.txt'); after=cycles('final-cycles.txt')
    bs=stacks('baseline-stack.tsv'); fs=stacks('final-stack.tsv')
    br=json.loads((DOCS/'baseline-resources.json').read_text())
    fr=json.loads((DOCS/'final-resources.json').read_text())
    stats=json.loads((DOCS/'accuracy.json').read_text())['functions']
    validation=json.loads((DOCS/'validation.json').read_text())
    assert validation['guest_suite_exit_code']==0
    assert all(s['failures']==0 and s['exceptional_changes']==0 for s in stats.values())
    assert br['interpreter_sha256']==fr['interpreter_sha256']
    dense={}
    for line in (DOCS/'dense.txt').read_text().splitlines():
        m=re.match(r'(\w+): (\d+) cases, max_abs (\S+) .*max_rel (\S+) .*max_ulp (\d+) .*failures (\d+)',line)
        if m:
            dense[m[1]]=dict(count=int(m[2]),absolute=float(m[3]),relative=float(m[4]),ulp=int(m[5]))
            assert int(m[6])==0
    out=['<!-- Generated by tests/math/report_phase34.py. -->',
         '# AVM math runtime — phases 3 and 4', '',
         'Measured on 2026-10-25 from working-tree baseline '
         '`b4ce2f611c8c47b86cd8386ab12f330b39f4895d`. The seven implementations '
         'are replaced outright; `sincosf` is added. The unfinished argument reducer, '
         'phase-2 exp/log/sqrt kernels, and interpreter are unchanged byte for byte. '
         'No native instructions or precision modes were added.', '',
         '## Performance', '',
         'Actual AVR interpreter cycles, RelWithDebInfo, identical 32-call inputs, '
         '`-O2` callers and `-O3 -ffp-contract=off` runtime math. Counts include loops, '
         'loads and result storage, subtracting the 35-cycle adjacent-break baseline. '
         'The sincos baseline uses separate sin/cos calls with the same inputs and sinks.', '',
         '| Function | Before cycles/call | After cycles/call | Speedup |',
         '|---|---:|---:|---:|']
    for fn,work in FUNCTIONS.items():
        key='math_'+work; b,a=before[key],after[key]
        out.append(f'| `{fn}` | {b/32:.2f} | {a/32:.2f} | {b/a:.3f}× |')
    out+=['','Large-angle reduction dominates the broad sin/cos/tan workloads and '
          'was deliberately left unchanged. The focused workloads show the kernel gains:', '',
          '| Workload | Before cycles/call | After cycles/call | Speedup |',
          '|---|---:|---:|---:|']
    focused=['sin_small','cos_small','tan_small','tan_reduced','atan2_ratios',
             'pow_bounded','pow_integer','pow_near_one','pow_extreme','hypot_scaled']
    for work in focused:
        key='math_'+work; b,a=before[key],after[key]
        out.append(f'| `{key}` | {b/32:.2f} | {a/32:.2f} | {b/a:.3f}× |')
    out+=['',f'New coverage workloads have no saved before measurement: integer crossover '
          f'{after["math_pow_crossover"]/32:.2f} cycles/call; exact hypot overflow neighbors '
          f'{after["math_hypot_boundary"]/32:.2f} cycles/call. The latter intentionally '
          'measures the cold exact-classification guard.', '',
          '## Numerical validation', '',
          f'The 100-digit mpmath search checked {sum(s["count"] for s in stats.values()):,} '
          'results with **zero acceptance failures and zero exceptional-value changes**. '
          'It combines deterministic random bits, every exponent, adjacent interval edges, '
          'near-one powers with large exponents, overflow/underflow boundaries, norm '
          'overflow neighbors, poles, quadrants and three local searches. The dense '
          'host-double sweep independently checks the same production sources. '
          'The table takes the larger observed maximum from those two searches.', '',
          '| Function | Maximum absolute error | Maximum relative error (normal reference) | Maximum ULP | Acceptance |',
          '|---|---:|---:|---:|---|']
    for fn in list(FUNCTIONS)[:-1]+['sincos_sinf','sincos_cosf']:
        s=stats[fn]; d=dense.get(fn,{})
        ab=max(s['max_absolute'],d.get('absolute',0))
        rel=max(s['max_relative_normal'],d.get('relative',0))
        ulp=max(s['max_ulp'],d.get('ulp',0))
        target={'powf':'relative ≤5e-5','hypotf':'≤4 ULP','tanf':'hybrid; see below',
                'atanf':'absolute ≤1e-6','atan2f':'absolute ≤1e-6'}.get(fn,'absolute ≤1e-5')
        out.append(f'| `{fn}` | {ab:.6g} | {rel:.6g} | {int(ulp)} | Pass: {target} |')
    tr=stats['tanf']['tangent_regions']
    tp=re.search(r'tanf_policy: away_max_absolute (\S+), away_max_budget_fraction (\S+), pole_max_ulp (\d+)',
                 (DOCS/'dense.txt').read_text())
    tan_abs=max(tr['away_from_poles']['max_absolute'],float(tp[1]))
    tan_fraction=max(tr['away_from_poles']['max_budget_fraction'],float(tp[2]))
    tan_poles=max(tr['pole_neighbors']['max_ulp'],int(tp[3]))
    out+=['',f'Tangent away from poles uses `1e-4 + 1e-4*abs(reference)`. The '
          f'combined searches observed maximum absolute error '
          f'{tan_abs:.6g} and used at most '
          f'{100*tan_fraction:.2f}% of that budget. '
          f'The pole-neighbor region (`abs(reference) >= 10000`) retains the '
          f'stricter four-ULP regression policy; the observed maximum was '
          f'{tan_poles} ULP there. The full-domain absolute '
          'maximum in the table occurs near a pole with a very large result. '
          'See `dense.txt` for the independent dense policy maxima.', '',
          'Exp/pow subnormals use the established absolute budget '
          '`rel_tol*2^-126 + 2^-149`, plus the relative term. NaNs compare by '
          'classification; infinity/zero signs, domain handling and exact fixtures '
          'remain strict. Atan boundary fixtures check local monotonicity around '
          '0.25, 0.5, 0.75, 1, 2 and 4. Sine/cosine reduction tails are omitted only '
          'inside the approximation kernels; the reducer and quadrant selection '
          'are untouched. Sampling and dense domains do not constitute an exhaustive '
          'proof over all binary32 pairs.', '',
          '## Selected implementations', '',
          '- **Power:** direct base-two composition; the phase-2 log normalization '
          'and degree-seven mantissa fit serve small exponents. A degree-eight '
          'log fit handles amplified errors for `abs(y)>8`. On '
          '`0.9375 <= abs(x) <= 1.125`, a degree-six log1p-series factor forms '
          '`y*(abs(x)-1)` first. Integer exponents through magnitude 16 use squaring '
          'with inversion first for negative powers; native-word bit classification '
          'gets parity without conversions or wide shift helpers. A cold '
          'two-component atanh-series product refinement resolves overflow and '
          'zero-underflow neighbors. Exact power-of-two logarithms bypass that '
          'series. The original general fdlibm engine is removed.',
          '- **Hypot:** unsorted, unscaled sum of squares for both magnitudes in '
          '`[2^-60,2^60)`; otherwise order magnitudes, discard an insignificant '
          'smaller operand, and scale by exact powers of two. A cold 50-bit '
          'squared-norm threshold comparison preserves overflow classification. '
          'Its two existing guest 64-bit helpers add no interpreter flash.',
          '- **Sine/cosine:** `x*P2(x*x)` (degree 5) and `P3(x*x)` (degree 6). '
          'Tiny inputs preserve signed zero and exact one. Fits include the '
          'rounded binary32 square of the reducer’s pi/4 endpoint.',
          '- **Tangent:** `x+x^3*P2(x*x)` (degree 7), one low-tail addition, '
          'and `-1/result` in odd quadrants. There is no pi/4 transform or '
          'compensated reciprocal.',
          '- **Atan/atan2:** four intervals on `[0,1]`, a degree-seven odd first '
          'piece and centered degree-four pieces elsewhere. Endpoint-constrained '
          'Remez fits remove observed backward boundary jumps. A balanced native-word '
          'decision tree selects coefficients. Atan reciprocates only above one; '
          'atan2 forms one smaller/larger quotient and shares the same kernel. '
          'NaNs, signed axes and infinities return through short branches.',
          '- **Shared sin/cos:** one existing argument reduction, one squared '
          'argument, both selected polynomials, then quadrant reconstruction. '
          'Standalone functions retain their own inlined evaluations.', '',
          'FPOLY embeds immediate coefficients and wins over ordinary Horner. '
          'Duplicating the inlined atan kernel across reciprocal/quadrant branches '
          'was faster than merging evaluation and carrying reconstruction state '
          'across it. Cold power refinement stays out of line to avoid common-path '
          'spills. Pow now references only `sqrtf`, removing the former wide shift, '
          '`expf` and `scalbnf` dependencies. Full instruction counts and undefined '
          'symbols are in the resource JSON; generated AVM disassembly is retained '
          'under `runtime/asm` and `bench/c/asm`.', '',
          '## Measured alternatives', '',
          'Rejected coefficients and trial source snapshots live only in the build '
          'tree. `candidates.json` records cycles and rejection counts. Representative '
          'trials below use total cycles per 32 calls, with the adjacent-break cost removed.', '',
          '| Candidate | Relevant workload | Cycles | Result |',
          '|---|---|---:|---|']
    candidates=json.loads((DOCS/'candidates.json').read_text())
    trials=[('initial','math_pow','Phase-2 log alone fails amplified-error/boundary cases'),
            ('trig-minimum','math_cos_small','Degree-four cosine fails the absolute budget'),
            ('trig-tan2','math_tan_reduced','Selected tangent degree'),
            ('trig-tan3','math_tan_reduced','Valid; slower'),
            ('trig-longer','math_sin_small','Valid; more coefficients cost cycles'),
            ('trig-horner','math_sincos','Valid; ordinary Horner is slower'),
            ('trig-two-pieces','math_cos_small','Cosine valid but slower; tangent fit fails'),
            ('atan-single5','math_atan','Degree-eleven odd fit fails'),
            ('atan-single6','math_atan2','Degree-thirteen fit valid; slower jointly'),
            ('atan-two3','math_atan','Shorter two-piece fit fails'),
            ('atan-four2','math_atan','Shorter four-piece fit fails'),
            ('atan-shared-four3','math_atan2','Merged evaluation increases spill costs'),
            ('atan-word-four3','math_atan','Fast linear tree; slower atan2 than balanced tree'),
            ('atan-balanced-four3','math_atan2','Balanced tree wins combined workloads'),
            ('anchored-atan','math_atan2','Endpoint anchoring improves continuity at equal cost')]
    for label,work,result in trials:
        c=candidates[label]
        out.append(f'| `{label}` | `{work}` | {c["cycles"][work]:,} | {result} |')
    out+=['', 'Integer-loop crossover trials used the same implementation and caller '
          'while varying only the maximum squaring exponent. These preceded the '
          'cold exact-power-of-two refinement optimization:', '',
          '| Maximum integer exponent | Integer workload cycles | Crossover workload cycles |',
          '|---:|---:|---:|']
    for n in [0,8,16,32,64,128]:
        c=candidates[f'pow-integer{n}']['cycles']
        out.append(f'| {n} | {c["math_pow_integer"]:,} | {c["math_pow_crossover"]:,} |')
    out+=['','Magnitude 16 is the fastest enabled crossover; 32 and 64 do not improve '
          'the ordinary integer workload. Disabling the loop reduces classification '
          'cost for fractional exponents but loses substantially on typical small '
          'integer powers. No implementation-selection framework remains in production.', '',
          '## Resource usage', '',
          'Object bytes include cold local functions. Linked images include program '
          'metadata, all dependencies and package padding. Coefficient immediates '
          'are already counted in object bytes.', '',
          '| Function object | Before bytes | After bytes | Change |',
          '|---|---:|---:|---:|']
    for fn,obj in OBJECTS.items():
        b,a=size(br,obj),size(fr,obj)
        out.append(f'| `{fn}` | {b} | {a} | {a-b:+d} |')
    out+=['','| Linked workload | Before bytes | After bytes | Change |',
          '|---|---:|---:|---:|']
    for work in FUNCTIONS.values():
        key='math_'+work; b,a=br['image_bytes'][key],fr['image_bytes'][key]
        out.append(f'| `{key}` | {b} | {a} | {a-b:+d} |')
    out+=['', 'Unique coefficient payloads: sine 12 bytes, cosine 16, tangent 12, '
          'atan 76, amplified-power log 32, near-one power 28 and boundary atanh '
          'tail 24. The reused exp polynomial has 20 bytes; the unchanged sqrt '
          'table has 8,192 bytes. FPOLY immediates can be duplicated by inlining; '
          'these payload counts are mathematical tables, not extra allocated RAM.', '',
          '| Workload | Before peak guest bytes | After peak guest bytes | After extra native bytes |',
          '|---|---:|---:|---:|']
    works=list(FUNCTIONS.values())+['pow_extreme','pow_near_one','hypot_boundary']
    for work in works:
        key='math_'+work; a=fs[key]; b=str(bs[key][0]) if key in bs else '—'
        out.append(f'| `{key}` | {b} | {a[0]} | {a[1]} |')
    out+=['',f'Maximum measured guest usage is **{max(x[0] for x in fs.values())}/256 '
          f'bytes**; maximum extra native math depth is '
          f'{max(x[1] for x in fs.values())} bytes. Stack stepping is a separate pass '
          'and does not alter cycle measurement. LLD stack checks remain enabled. '
          'The ISR and active SPI/FPOLY compatibility checks passed.', '',
          f'Interpreter flash data: **{validation["interpreter_flash_bytes"]:,} bytes '
          '(change 0)**. Before/after HEX SHA-256: '
          f'`{fr["interpreter_sha256"]}`. `provenance.json` also verifies both '
          'argument-reduction files and the phase-2 exp/log/sqrt source/table hashes.', '',
          '## Validation and reproduction', '',
          f'All **{validation["guest_test_count"]} guest tests** passed at '
          '`-O0`, `-O1`, `-O2`, `-O3`, `-Os`, `-Oz`. The production math archive '
          'remains built at `-O3`; these are the six supported caller configurations. '
          'The complete suite also passed dense math, the 16,777,216 normalized '
          'sqrt mantissa/parity cases, all 8,388,607 positive subnormals, all '
          '8,388,608 normalized mantissas for the reducer-product check, exact rounding/remainder checks, '
          'FPOLY interruption/SPI preservation, 64 native audio cases, large C/C++ '
          'audio assets, timer/watchdog, display and stack-bound tests. '
          'See `validation.json` and the retained logs.', '',
          'Use the existing generator/compiler and initialize the MSVC environment '
          'matching `build/CMakeCache.txt` on Windows. Install '
          '`tests/math/requirements.txt` in the reference Python. From the repository root:', '',
          '```sh',
          'python tests/math/phase34_coefficients.py --sin 2 --cos 3 --tan 2 --output runtime/lib/math/trig_poly.h',
          'python tests/math/phase34_coefficients.py --atan 3 --pieces 4 --balanced --anchor-ends --output runtime/lib/math/atan_poly.h',
          'python tests/math/phase34_coefficients.py --pow-log-degree 8 --output runtime/lib/math/pow_log_poly.h',
          'python tests/math/run_candidate.py --label final --output build/math-phase34 --stack --functions powf hypotf sinf cosf tanf atanf atan2f sincos_sinf sincos_cosf',
          'python tests/math/accuracy_reference.py --output docs/math-runtime/phase34/accuracy.json --samples 10000 --fixtures --functions powf hypotf sinf cosf tanf atanf atan2f sincos_sinf sincos_cosf',
          'cmake --build build --config RelWithDebInfo --target avm_tests_run avm_audio_tests_run avm_runtime_asm --parallel 8 > build/math-phase34/regressions-final.log 2>&1',
          'python tests/math/generate_sqrt_table.py --check',
          'python tests/math/report_phase34.py --refresh',
          '```', '',
          'For additional degree/interval/crossover trials, run '
          '`python tests/math/sweep_phase34.py trig`, `atan`, or `power`. '
          'The sweep restores production sources even on failure; rebuild afterward '
          'to replace the final trial objects. Prototype code-layout trials in the '
          'candidate record additionally predate the selected branch layout. '
          'Baseline measurements are preserved data, so no old algorithm source '
          'or permanent A/B library is needed to reproduce the current results.', '']
    (DOCS/'report.md').write_text('\n'.join(out),encoding='utf-8')


if __name__=='__main__': main()
