#!/usr/bin/env python3
"""Compile AVM audio JSON to bounded event bytes or an AVM_PROGMEM C array."""
import argparse
import json
import re
from pathlib import Path

INSTRUMENTS = {"square": 0, "bass": 1, "lead": 2, "noise": 3}


def note_number(value):
    if value is None:
        return 0x80
    if isinstance(value, str):
        match = re.fullmatch(r"([A-Ga-g])([#b]?)(-?\d+)", value)
        if not match:
            raise ValueError(f"invalid note {value!r}")
        name, accidental, octave = match.groups()
        value = 12 * (int(octave) + 1) + dict(C=0, D=2, E=4, F=5, G=7, A=9, B=11)[name.upper()]
        value += {"": 0, "#": 1, "b": -1}[accidental]
    if not isinstance(value, int) or not 24 <= value <= 95:
        raise ValueError("notes must be MIDI 24..95 (C1..B6)")
    return value


def delta_bytes(ticks):
    if not isinstance(ticks, int) or not 0 <= ticks <= 65535:
        raise ValueError("delta must be 0..65535 ticks")
    return bytes([ticks]) if ticks < 255 else bytes([255, ticks & 255, ticks >> 8])


def compile_song(song):
    """delta is in rows; row_ticks defaults to one 4 ms tick.

    Instrument, volume, then note changes use zero-delay passes through the
    same channel mask. Retained volume costs no bytes in later note events.
    """
    mask = song.get("mask", 15)
    if not isinstance(mask, int) or not 1 <= mask <= 15:
        raise ValueError("mask must be 1..15")
    output = bytearray([0xA1, mask])
    period = song.get("row_ticks", 1)
    duration = 0
    zero_run = 0
    leading_zero = 0
    seen_time = False
    for event in song.get("events", []):
        period = event.get("row_ticks", period)
        if not isinstance(period, int) or period < 1:
            raise ValueError("row_ticks must be a positive integer")
        ticks = event.get("delta", 0) * period
        delta = delta_bytes(ticks)
        duration += ticks
        changes = [{}, {}, {}]
        for channel, update in event.get("channels", {}).items():
            channel = int(channel)
            if not 0 <= channel < 4 or not mask & (1 << channel):
                raise ValueError("channel outside ownership mask")
            if not isinstance(update, dict):
                update = {"note": update}
            if set(update) - {"note", "volume", "instrument"}:
                raise ValueError("unknown channel field")
            if "instrument" in update:
                changes[0][channel] = 0xC0 + INSTRUMENTS[update["instrument"]]
            if "volume" in update:
                v = update["volume"]
                if not isinstance(v, int) or not 0 <= v <= 31:
                    raise ValueError("channel volume must be 0..31")
                changes[1][channel] = 0xA0 + v
            if "note" in update:
                changes[2][channel] = note_number(update["note"])
        passes = [c for c in changes if c] or [{}]
        for changes in passes:
            if delta == b"\0":
                zero_run += 1
                if not seen_time:
                    leading_zero += 1
            else:
                zero_run = 1
                seen_time = True
            if zero_run > 63:
                raise ValueError("too many simultaneous changes for the native event budget")
            output += delta
            output.append(sum(1 << c for c in changes))
            output += bytes(changes[c] for c in sorted(changes))
            delta = b"\0"
    ticks = song.get("end_delta", 0) * period
    duration += ticks
    if song.get("loop", False) and duration == 0:
        raise ValueError("a loop must have positive duration")
    zero_run = zero_run + 1 if ticks == 0 else 1
    if zero_run > 63 or (song.get("loop", False) and zero_run + leading_zero > 63):
        raise ValueError("too many simultaneous changes across the end/loop boundary")
    output += delta_bytes(ticks)
    output.append(0x80 if song.get("loop", False) else 0x40)
    if len(output) > 65535:
        raise ValueError("asset exceeds uint16 byte length")
    return bytes(output)


def c_array(data, name):
    if not re.fullmatch(r"[A-Za-z_]\w*", name):
        raise ValueError("invalid C identifier")
    rows = ["    " + ", ".join(f"0x{x:02x}" for x in data[i:i+16]) + "," for i in range(0, len(data), 16)]
    return "/* Generated by avm_music.py. */\n#include <avm/audio.h>\nstatic const uint8_t AVM_PROGMEM " + name + "[] = {\n" + "\n".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--name", help="emit a C array with this identifier")
    args = parser.parse_args()
    try:
        data = compile_song(json.loads(args.source.read_text(encoding="utf-8")))
        args.output.parent.mkdir(parents=True, exist_ok=True)
        if args.name:
            args.output.write_text(c_array(data, args.name), encoding="utf-8")
        else:
            args.output.write_bytes(data)
    except (ValueError, KeyError, TypeError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
