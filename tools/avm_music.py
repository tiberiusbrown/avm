#!/usr/bin/env python3
"""Compile AVM audio JSON to bounded event bytes or an AVM_PROGMEM C array."""
import argparse
import json
import re
from pathlib import Path

WAVEFORMS = {"square": 0, "triangle": 1, "sawtooth": 2, "sine": 3}


def note_number(value):
    if value is None:
        return 0x80
    if isinstance(value, str):
        match = re.fullmatch(r"([A-Ga-g])([#b]?)(-?\d+)", value)
        if not match:
            raise ValueError(f"invalid note {value!r}")
        name, accidental, octave = match.groups()
        value = 12 * (int(octave) + 1) + dict(C=0, D=2, E=4, F=5, G=7, A=9, B=11)[name.upper()]
        value += {"": 0, "#": 1, "b": -1}[accidental]
    if not isinstance(value, int) or not 24 <= value <= 95:
        raise ValueError("notes must be MIDI 24..95 (C1..B6)")
    return value


def delta_bytes(ticks):
    if not isinstance(ticks, int) or not 1 <= ticks <= 256:
        raise ValueError("encoded delta must be 1..256 ticks")
    return bytes([ticks - 1])


def emit_event(output, ticks, payload):
    if not isinstance(ticks, int) or ticks < 1:
        raise ValueError("delta must be a positive integer number of ticks")
    continues = (ticks - 1) // 256
    if len(output) + 3 * continues + 1 + len(payload) > 65535:
        raise ValueError("asset exceeds uint16 byte length")
    output += bytes([255, 0, 0]) * continues
    output += delta_bytes(ticks - 256 * continues)
    output += payload


def compile_song(song):
    """delta is in rows; row_ticks defaults to one 4 ms tick.

    Every event waits at least one tick. Long waits use Continue records;
    Note and volume/waveform changes share one packed-mask event. The first
    event initializes every owned channel, including channels starting silent.
    """
    mask = song.get("mask", 15)
    if not isinstance(mask, int) or not 1 <= mask <= 15:
        raise ValueError("mask must be 1..15")
    output = bytearray([0xA2, mask])
    period = song.get("row_ticks", 1)
    if not isinstance(period, int) or period < 1:
        raise ValueError("row_ticks must be a positive integer")
    notes = [0x80] * 4
    volumes = [24] * 4
    waveforms = [0] * 4
    first = True
    for event in song.get("events", []):
        period = event.get("row_ticks", period)
        if not isinstance(period, int) or period < 1:
            raise ValueError("row_ticks must be a positive integer")
        rows = event.get("delta", 1)
        if not isinstance(rows, int) or rows < 1:
            raise ValueError("delta must be a positive integer number of rows")
        ticks = rows * period
        changes = [{}, {}]
        for channel, update in event.get("channels", {}).items():
            channel = int(channel)
            if not 0 <= channel < 4 or not mask & (1 << channel):
                raise ValueError("channel outside ownership mask")
            if not isinstance(update, dict):
                update = {"note": update}
            if set(update) - {"note", "volume", "waveform"}:
                raise ValueError("unknown channel field")
            if "volume" in update:
                v = update["volume"]
                if not isinstance(v, int) or not 0 <= v <= 31:
                    raise ValueError("channel volume must be 0..31")
                volumes[channel] = v
            if "waveform" in update:
                wave = update["waveform"]
                if not isinstance(wave, str) or wave not in WAVEFORMS:
                    raise ValueError("waveform must be square, triangle, sawtooth, or sine")
                waveforms[channel] = WAVEFORMS[wave]
            if "volume" in update or "waveform" in update:
                changes[1][channel] = (waveforms[channel] << 5) | volumes[channel]
            if "note" in update:
                notes[channel] = note_number(update["note"])
                changes[0][channel] = notes[channel]
        if first:
            for channel in range(4):
                if mask & (1 << channel):
                    changes[0][channel] = notes[channel]
                    changes[1][channel] = (waveforms[channel] << 5) | volumes[channel]
            first = False
        packed = sum(1 << c for c in changes[0]) | sum(16 << c for c in changes[1])
        payload = bytes([packed]) + bytes(changes[p][c] for p in range(2) for c in sorted(changes[p]))
        emit_event(output, ticks, payload if packed else bytes([0, 0]))
    rows = song.get("end_delta", 1)
    if not isinstance(rows, int) or rows < 1:
        raise ValueError("end_delta must be a positive integer number of rows")
    emit_event(output, rows * period, bytes([0, 2 if song.get("loop", False) else 1]))
    return bytes(output)


def c_array(data, name):
    if not re.fullmatch(r"[A-Za-z_]\w*", name):
        raise ValueError("invalid C identifier")
    rows = ["    " + ", ".join(f"0x{x:02x}" for x in data[i:i+16]) + "," for i in range(0, len(data), 16)]
    return "/* Generated by avm_music.py. */\n#include <avm/audio.h>\nstatic const uint8_t AVM_PROGMEM " + name + "[] = {\n" + "\n".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--name", help="emit a C array with this identifier")
    args = parser.parse_args()
    try:
        data = compile_song(json.loads(args.source.read_text(encoding="utf-8")))
        args.output.parent.mkdir(parents=True, exist_ok=True)
        if args.name:
            args.output.write_text(c_array(data, args.name), encoding="utf-8")
        else:
            args.output.write_bytes(data)
    except (ValueError, KeyError, TypeError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
